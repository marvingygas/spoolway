//! Pure rendering: turning [`super::Board`]'s data into terminal output.
//!
//! Nothing here reads a task file, a lane list or the ledger — every
//! function takes the data it draws (a `&[Row]`, a `&Board`'s own fields) and
//! returns a `String`. [`super`] is the half that gathers that data; this is
//! the half that draws it.

use super::*;

/// The gap between columns of the task table, and of the RECENT ticker's own
/// grid — see [`ticker`].
///
/// Three, not two: every column already sizes itself to the widest value
/// among the rows it is drawing, so the only thing that ever made two
/// columns read as one was the gutter between them.
pub(super) const GUTTER: &str = "   ";

/// The table's own left margin — the same one column the masthead, the
/// ticker, the footer and the key line already use, so the block lines up
/// with the rest of the frame. Every line of the table starts here: the
/// header, a task row, a group's band and its closing total line alike.
/// Right after it comes the two-column cursor gutter — see
/// [`CURSOR_GUTTER_WIDTH`] — on every one of those lines but the band, which
/// sits at the margin itself, outdented past the gutter so it reads as a
/// heading rather than a row.
const MARGIN: &str = " ";

/// The gap that stands between TASK and STEP once PIPELINE has been dropped
/// for width — see [`table`]. Six spaces because both sides hold free
/// text — a task id, a step name — neither of them a figure and neither of
/// them coloured, so at one gutter they would read as one run-on phrase
/// however well they are padded. Every other boundary has a shape change to
/// separate it; this one has to buy the separation in space.
const TASK_GAP: &str = "      ";

/// What sits in a column that has no figure — a queued task's context, a
/// step nothing has been spent at yet. Dimmed where there is colour: the
/// board says nothing rather than printing a number it cannot stand behind.
const NOTHING: &str = "—";

/// The width of the cursor gutter — see [`CURSOR_MARK`] and [`NO_CURSOR`] —
/// between [`MARGIN`] and TASK. Drawn on every row, on the header and on a
/// group's closing total line alike, whether or not the board has a cursor
/// at all, so a highlighted row costs the rest of the line nothing: no
/// column ever moves when the cursor does. A `char` count, not a byte
/// count — [`CURSOR_MARK`]'s arrow is three bytes wide and two columns wide,
/// same as the two spaces of [`NO_CURSOR`].
const CURSOR_GUTTER_WIDTH: usize = 2;

/// What marks the row the board's cursor sits on, drawn in the gutter in
/// front of the TASK cell it points at — the mark itself and the one column
/// of space that stands between it and TASK.
const CURSOR_MARK: &str = "▸ ";

/// What every other row draws in the same two columns [`CURSOR_MARK`] would
/// otherwise occupy — the header and a group's closing total line included,
/// since neither is ever the row the cursor sits on.
const NO_CURSOR: &str = "  ";

/// The lockup — the spool mark and the pixel wordmark — as half-block art, one
/// row set per frame of the mark.
///
/// Generated by `docs/logo/generate_board.py`; `the_board_art_is_what_the_generator_draws`
/// fails if this constant and that script disagree, so it is never edited by
/// hand. Paste what the script prints.
///
/// Two frames because the mark has two hand-drawn ones, thread on opposite
/// phases — see `docs/logo/mark.py`. `masthead` takes which frame to draw:
/// the board picks between them off the wall clock while at least one row is
/// running, and holds frame 0 — the logo exactly as it ships — the moment
/// nothing is, the same as `banner` and every other caller.
///
/// A half-block splits the cell 1x2, which makes each pixel square, because a
/// character cell is about twice as tall as it is wide. That is the whole
/// reason for the shape: the sextants this replaced split it 2x3, so every
/// pixel came out a third taller than wide, the design had to be stretched 4/3
/// before packing, and the stretch then had to be hand-repaired wherever it
/// doubled a one-pixel stroke. Square pixels need no correction, so there is
/// nothing here a person approved.
///
/// The mark is drawn at the wordmark's own block size — one design pixel of the
/// spool is one design pixel of the type — and sits on the letters' baseline.
/// It is never scaled to match the wordmark's height: that height is mostly the
/// ascender on `l` and the descenders on `p` and `y`, so matching it makes the
/// mark tower over the letters, and scaling coarsens its blocks against theirs
/// besides. The two are one piece of pixel art, not an icon beside some type.
///
/// It stays 1-bit and draws in the default foreground, which is what makes it
/// right on a light terminal and a dark one. Colouring the halves separately
/// would buy antialiasing, but antialiasing is partial coverage of a known
/// ground, and the board does not know the terminal's background.
