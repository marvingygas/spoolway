    /// Escape codes are invisible and the dot is three bytes, so a column
    /// padded by either goes out of line. Everything is padded by what a
    /// reader can actually see.
    #[test]
    fn a_dot_and_a_colour_code_never_shift_a_column() {
        let repo = fixture("columns");
        let pipelines = Pipelines::builtin();
        add(&repo, "login", &[], Some("implement"));
        add(&repo, "sessions", &["login"], None);

        let rows = rows(&repo, &pipelines).unwrap();
        let painted = strip(&table(&rows, Style::board(200), &BTreeMap::new(), None));
        // Columns, not bytes: `●` is three bytes and `—` is three more, which
        // is the whole reason a column can go out of line here.
        let at = |line: &str, of: &dyn Fn(char) -> bool| line.chars().position(of).expect(line);
        let starts = |line: &str, column: &str| {
            line.match_indices(column)
                .next()
                .map(|(byte, _)| line[..byte].chars().count())
                .expect(line)
        };
        let header = painted.lines().next().unwrap();

        for id in ["login", "sessions"] {
            let row = painted.lines().find(|l| l.contains(id)).unwrap();
            assert_eq!(
                at(row, &|c| c == '●' || c == '○'),
                starts(header, "STATE"),
                "{row}\n{header}"
            );
            // Both figures are right-aligned, so a one-character dash ends
            // where a four-character `100%` would — under CTX's last column.
            assert_eq!(
                at(row, &|c| c == '—'),
                starts(header, "CTX") + "CTX".len() - 1,
                "{row}\n{header}"
            );
        }
    }

