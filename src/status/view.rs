pub(crate) const RESET: &str = "\x1b[0m";

pub(crate) const BOLD: &str = "\x1b[1m";

pub(crate) const DIM: &str = "\x1b[2m";

const GREEN: &str = "\x1b[32m";

pub(super) const AMBER: &str = "\x1b[33m";

// The colour of `Blocked`, and of `Unknown`, a task on a step its pipeline
// does not have. Not red: a block is a task waiting on a person, the same
// *kind* of stop `Paused` is, and red reads as something gone wrong rather
// than something to look at. Orange rather than amber too, so a block and a
// `Paused` row never read as the same colour from across a room.
const ORANGE: &str = "\x1b[38;5;208m";

/// The two halves of an OSC 8 terminal hyperlink: `OSC8 <url> ST <label> OSC8
/// ST`. `ST` here is `ESC \`, the string terminator — a hyperlink escape has
/// no `m` in it, which is why [`strip_ansi`] needs a branch of its own for it.
pub(super) const OSC8: &str = "\x1b]8;;";
pub(super) const ST: &str = "\x1b\\";

impl State {
    /// What the state reads as, with nothing invisible in it. The dot is part
    /// of the word: it is what carries the colour, and a plain-text table wants
    /// the same column width as a coloured one.
    pub fn word(self) -> &'static str {
        match self {
            State::Paused => "● paused",
            State::HookFailed => "● hook failed",
            State::Running => "● running",
            State::Silent { .. } => "● silent",
            State::Starting => "◌ starting",
            State::Finished => "✓ finished",
            State::Blocked => "● blocked",
            State::Unknown => "● unknown",
            State::Prompt => "● prompt",
            State::Queued => "○ queued",
            State::Waiting => "○ waiting",
            State::Held => "○ held",
            State::Done => "● done",
        }
    }

    fn dot(self) -> String {
        let word = self.word();
        match self {
            // Amber, and bold: a paused task is a step that went *well* and
            // is now the one thing on the board a person can act on — whether
            // it is a gate to release or a pane to look at.
            State::Paused => format!("{AMBER}{BOLD}{word}{RESET}"),
            // Amber, and bold, like `Paused`: the task waits on a person's
            // key, and the work behind it may well have gone fine — only the
            // hook reporting it to the tracker did not.
            State::HookFailed => format!("{AMBER}{BOLD}{word}{RESET}"),
            State::Running => format!("{GREEN}{word}{RESET}"),
            // Amber, as the stops a person answers are, but not bold like
            // them: a silent lane may be a usage limit that clears by
            // itself, so it is something to look at rather than a stop
            // that waits on a key.
            State::Silent { .. } => format!("{AMBER}{word}{RESET}"),
            // Running's own colour: the dispatcher is working this task, it
            // is only that the agent is not up yet. The hollow dot is what
            // tells the two apart.
            State::Starting => format!("{GREEN}{word}{RESET}"),
            // Dim, not `Running`'s green: nothing is working this step any
            // more, and the board's green means something is.
            State::Finished => format!("{DIM}{word}{RESET}"),
            State::Blocked => format!("{ORANGE}{word}{RESET}"),
            // Orange like `Blocked`: the task is stopped until a person
            // looks at it, and nothing about it came back as a bad verdict.
            State::Unknown => format!("{ORANGE}{word}{RESET}"),
            // Amber, and bold, like `Paused`: a prompt is a pane holding a
            // permission question, and nothing moves until a person answers
            // it there — the same stop that `Paused` is.
            State::Prompt => format!("{AMBER}{BOLD}{word}{RESET}"),
            State::Queued => format!("{DIM}{word}{RESET}"),
            State::Waiting => format!("{DIM}{word}{RESET}"),
            State::Held => format!("{DIM}{word}{RESET}"),
            State::Done => format!("{DIM}{word}{RESET}"),
        }
    }
}

/// One thing the RECENT ticker witnessed, kept as data rather than a
/// finished line — so the width, the order and the clip are all decided in
/// [`ticker`], against the pane and the rest of the block, and not at the
/// moment the move was first seen.
#[derive(Clone)]
pub(crate) enum RecentEvent {
    /// A task's move, classified once by `classify` in the parent module
    /// from the task file and pipeline as they stood when the board saw it,
    /// and worded by [`sentence`].
    Arrival {
        at: String,
        id: String,
        /// The routine the task is a queued copy of, from
        /// [`crate::task::Task::routine`], read off the task file the move
        /// was classified against. RECENT draws it in place of `id` — see
        /// [`RecentEvent::name`] — and keeps one line per routine on it —
        /// see [`RecentEvent::key`]. `None` on a task queued any other way,
        /// and on a copy whose line was edited away or left blank.
        routine: Option<String>,
        change: Move,
    },
}

impl RecentEvent {
    /// What the RECENT line names the task by: the routine a queued copy
    /// was made from, and the id otherwise — the same rule as
    /// [`Row::name`]. The id's `-N` only keeps two runs' files apart, and
    /// RECENT is read by a person, never handed back to a command.
    pub(crate) fn name(&self) -> &str {
        let RecentEvent::Arrival { id, routine, .. } = self;
        routine.as_deref().unwrap_or(id)
    }

    /// Which line of RECENT this event replaces: every copy of one routine
    /// shares a line, and any other task has one of its own. The two kinds
    /// are kept apart so a plain task whose id happens to equal a routine's
    /// name never folds into that routine's line.
    pub(crate) fn key(&self) -> RecentKey<'_> {
        match self {
            RecentEvent::Arrival {
                routine: Some(routine),
                ..
            } => RecentKey::Routine(routine),
            RecentEvent::Arrival { id, .. } => RecentKey::Task(id),
        }
    }
}

/// The line of RECENT an event belongs to — see [`RecentEvent::key`].
#[derive(Debug, PartialEq, Eq)]
pub(crate) enum RecentKey<'a> {
    Routine(&'a str),
    Task(&'a str),
}

/// What a task did to move, and between which steps. Each variant is one
/// fixed sentence — see [`sentence`], the only place any of them is worded.
#[derive(Clone, Debug, PartialEq)]
pub(crate) enum Move {
    /// The task left `queued` for its first step.
    Started { to: String },
    /// `from` reported a pass — or, for a command step, which reports
    /// nothing, exited into its own `on_pass`. `to` is `done` for a task the
    /// archive holds as finished.
    Passed {
        from: String,
        to: String,
        cause: Option<Cause>,
    },
    /// `from` reported a failure, or a command step exited into its own
    /// `on_fail` — `blocked` when it declares none.
    Failed {
        from: String,
        to: String,
        cause: Option<Cause>,
    },
    /// `from` was walked past without running: named by the task's own
    /// `skip:`, a `first:` or `last:` step out of place in its chain, or an
    /// agent step that sent no report before it moved on down its `on_pass`.
    Skipped {
        from: String,
        to: String,
        cause: Option<Cause>,
    },
    /// `from`'s lane said so itself, with `--block` or `--pause`.
    Reported {
        what: Reported,
        from: String,
        to: String,
        cause: Option<Cause>,
    },
    /// `from`'s lane never got going: refused at launch, or gone before it
    /// reported anything.
    CouldNotLaunch {
        from: String,
        to: String,
        cause: Option<Cause>,
    },
    /// Any other move into `paused`. `None` is a task stopped while still on
    /// `queued`, which has no step to name.
    Stopped {
        from: Option<String>,
        cause: Option<Cause>,
    },
    /// `from`'s lane was stopped by the dispatcher — it ended its turn
    /// without reporting, held a child past `dispatch.lane_child_ceiling`, or
    /// crossed `session_blocked_ctx` — and an unattended run sent the task to
    /// `to`, `blocked`, for the unblocker lane. An attended run parks the same
    /// stop on `paused`, which is [`Move::Stopped`] with [`Cause::Escalated`].
    Escalated { from: String, to: String },
    /// An issue-tracking hook failed and the task moved to `hook_failed`.
    /// `event` is the hook that failed, from `hook_paused:`, and `reason` is
    /// why, from `hook_error:`; either is `None` on a file that lacks it.
    /// `passed` names the step whose pass carried the task to `done`, when
    /// it was the `done` hook that failed and the step can be told.
    HookFailed {
        passed: Option<String>,
        event: Option<String>,
        reason: Option<String>,
    },
    /// The hook `event` that held the task on `hook_failed` was skipped, by
    /// `spoolway resume --skip-hook` or the board's `k`. `to` is where it
    /// moved — `queued` first, then the step it starts on — or `None` for a
    /// `done` hook's skip, which archives it.
    HookSkipped { event: String, to: Option<String> },
    /// The task was on `paused` or `hook_failed`.
    Resumed { to: String },
    /// The task was on `blocked`. `by_lane` when the report that moved it
    /// came from a lane working `blocked` itself, rather than a person's
    /// resume.
    Unblocked { to: String, by_lane: bool },
    /// Nothing above explains the move. Named plainly rather than guessed at.
    Left { from: String, to: String },
}

/// What a lane reported on its way out, for [`Move::Reported`] — the two
/// outcomes that are neither a pass nor a fail.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(crate) enum Reported {
    Block,
    Pause,
}

/// Why a task stopped, when the route alone does not say: the part of a
/// sentence drawn in brackets after `moved to <step>`. Each is read from a
/// field the task file already carries — see `classify` in the parent module.
#[derive(Clone, Debug, PartialEq)]
pub(crate) enum Cause {
    /// The step's own `gate: true` held its pass.
    Gate,
    /// The task's own `gate_at` held the step's outcome.
    Scheduled,
    /// A person parked it: the board's `pause`, or an Escape in the pane.
    Manually,
    /// The dispatch tab's stop popup parked it.
    DispatchingStopped,
    /// The dispatcher gave up on the lane.
    Escalated,
    /// The branch the task starts from does not exist.
    BranchMissing(String),
    /// The step the move would have reached had spent its `loop:`.
    LoopLimit(String),
    /// The launch was refused this many times in a row.
    Attempts(u32),
    /// The lane was launched and left nothing behind.
    LaneDiedAtLaunch,
    /// A pass into `done` found work in the worktree it could not commit.
    UncommittedWork,
}

impl Cause {
    fn words(&self) -> String {
        match self {
            Cause::Gate => "gate".into(),
            Cause::Scheduled => "scheduled".into(),
            Cause::Manually => "manually".into(),
            Cause::DispatchingStopped => "dispatching stopped".into(),
            Cause::Escalated => "escalated".into(),
            Cause::BranchMissing(branch) => format!("branch {branch} missing"),
            Cause::LoopLimit(step) => format!("loop limit on {step}"),
            Cause::Attempts(n) => format!("{n} attempts"),
            Cause::LaneDiedAtLaunch => "lane died at launch".into(),
            Cause::UncommittedWork => "uncommitted work".into(),
        }
    }
}

/// [`BoardMode::ConfirmPause`]'s panel, `pause`'s own, titled with the
/// task's `name`: one abort, so the body names the step it is on directly
/// rather than repeating the task the title already names. A command step adds two lines saying what pausing
/// does to it, since unlike an agent's turn its process is ended and its run
/// starts over; an agent step needs no such warning.
///
/// Its answers are [`pause_answers`].
pub(super) fn pause_confirm_panel(
    name: &str,
    abort: &Abort,
    scheduled: bool,
    cursor: usize,
) -> Vec<String> {
    let time = abort
        .elapsed
        .map(|d| human_secs(d.as_secs() as i64))
        .unwrap_or_else(|| NOTHING.to_string());
    let mut body = vec![
        "Pausing aborts the step it is on:".to_string(),
        String::new(),
        format!("{}    {}    {time}", abort.step, abort.kind.word()),
    ];
    if matches!(abort.kind, AbortKind::Command) {
        body.push(String::new());
        body.push("Pausing terminates the command's process.".to_string());
        body.push("Resuming restarts the command.".to_string());
    }
    crate::screen::ask(
        &format!("pause {name}"),
        &body,
        &pause_answers(abort, scheduled),
        cursor,
    )
}

/// [`pause_confirm_panel`]'s answers, which the board's key handling also
/// counts to move the cursor: pause now, or leave the step running and pause
/// when it finishes. The second names the step, and reads `cancel the
/// scheduled pause` instead while `scheduled` says that step already has one,
/// since answering it then clears the schedule — see
/// `Board::on_key_pause_confirm`.
pub(super) fn pause_answers(abort: &Abort, scheduled: bool) -> [String; 2] {
    let later = match scheduled {
        true => "cancel the scheduled pause".to_string(),
        false => format!("pause when {} finishes", abort.step),
    };
    ["pause now".to_string(), later]
}

/// How wide [`restart_confirm_panel`] wraps its closing sentence: wide enough
/// to keep `The lane is torn down and `review-spec` is briefed from` on one
/// row, and narrow enough that the panel stays inside an 80-column pane.
const RESTART_WRAP: usize = 56;

/// [`BoardMode::ConfirmRestart`]'s panel, `restart`'s own: the step, the lane
/// and the session a restart throws away, then what happens to them, so a
/// person sees exactly which conversation they are giving up before they
/// answer.
///
/// The session row is left out when none is on record — a lane that never
/// got as far as a turn — rather than printed empty, the same as
/// `spoolway restart` prints no session line then. A refusal its answer met
/// is printed under the closing sentence, above the one answer, `restart`.
///
/// A command step has no lane and no session, so its form names the step and
/// the run in their place, and says the command's process is ended and run
/// again. When no run is going, on a task paused on or blocked off the step,
/// the `run` row is left out and the closing sentence only says the step runs
/// again, since there is no process left to end.
pub(super) fn restart_confirm_panel(confirm: &RestartConfirm) -> Vec<String> {
    let mut body = Vec::new();
    // The command form opens on a blank row that sets its two short rows
    // apart from the title; the agent form keeps the rows it has always had.
    if matches!(confirm.ends, RestartEnds::Command { .. }) {
        body.push(String::new());
    }
    body.push(format!("step      {}", confirm.step));
    let closing = match &confirm.ends {
        RestartEnds::Agent { lane, session } => {
            body.push(format!("lane      {lane}"));
            if let Some(session) = session {
                body.push(format!("session   {}", session.describe()));
            }
            format!(
                "The lane is torn down and `{}` is briefed from scratch. Its conversation is not \
                 kept.",
                confirm.step
            )
        }
        RestartEnds::Command {
            elapsed: Some(elapsed),
        } => {
            body.push(format!(
                "run       {} · {}",
                AbortKind::Command.word(),
                human_secs(elapsed.as_secs() as i64)
            ));
            format!(
                "The command's process is ended and `{}` runs again from the start. Its log is \
                 kept as the previous log.",
                confirm.step
            )
        }
        // No run is going: a pause already ended its process, or it exited
        // on its own. Saying the restart ends one would name a process that
        // is not there.
        RestartEnds::Command { elapsed: None } => format!(
            "`{}` runs again from the start. Its log is kept as the previous log.",
            confirm.step
        ),
    };
    body.push(String::new());
    body.extend(crate::screen::wrap(&closing, RESTART_WRAP));
    if let Some(err) = &confirm.error {
        body.push(String::new());
        body.extend(
            err.lines()
                .flat_map(|l| crate::screen::wrap(l, crate::screen::NOTICE_WRAP)),
        );
    }
    crate::screen::ask(
        &format!("restart {}", confirm.name),
        &body,
        &["restart".to_string()],
        0,
    )
}

/// [`BoardMode::ResumePicker`]'s panel: where the task stopped, a refusal
/// if `enter` met one, then the answers — its pipeline's steps with any
/// pinned row under them, drawn by [`crate::screen::ask`] with `>` on the
/// cursor's row — and the key row every answer list closes on.
///
/// `height` is [`pane_height`]'s: the list shows as many steps as the pane
/// leaves room for, with `▲ n more` and `▼ n more` standing in for the rest,
/// so a long pipeline in a short pane keeps the cursor's row and the key line
/// on screen. A refusal keeps its first line whatever the pane — the whole
/// point of printing one is that a refused `enter` does not look like
/// nothing happened — and is cut, ending in `…`, before the list drops under
/// its three-row least. Past that it is the list that gives way, down to the
/// cursor's row alone — see [`list_window`]. Only a pane too short for the
/// panel's fixed rows, that row and the refusal's first line still
/// overflows. `None` — no terminal to measure — shows every step and the
/// whole refusal.
pub(super) fn resume_picker_panel(picker: &ResumePicker, height: Option<usize>) -> Vec<String> {
    // Three columns past the longest step id, so every note starts in one
    // column however long the pipeline's own step names are.
    let column = picker
        .rows
        .iter()
        .map(|row| row.step.chars().count())
        .max()
        .unwrap_or(0)
        + 3;
    let line = |i: usize| {
        let row = &picker.rows[i];
        let text = format!("{}{}", crate::screen::pad_to(&row.step, column), row.note);
        text.trim_end().to_string()
    };
    let mut error: Vec<String> = match &picker.error {
        Some(err) => std::iter::once(String::new())
            .chain(
                err.lines()
                    .flat_map(|l| crate::screen::wrap(l, crate::screen::NOTICE_WRAP)),
            )
            .collect(),
        None => Vec::new(),
    };
    let pinned = picker.rows.len() - picker.listed;

    // Every row but the list's own and the refusal's: the two borders, a
    // blank and the header, a blank above the list; the pinned rows under
    // it; and a blank and the key row to close. Three more rows are kept
    // spare, because `with_popup` pads a frame shorter than the panel plus
    // two, and the unhosted board's frame is one row short of the pane —
    // see `clamp_rows`. A panel more than three rows short of the pane is
    // never padded past it.
    let fixed = 2 + 2 + 1 + pinned + 2 + 3;
    // A pinned `done` row is set apart from the steps by a blank line above
    // it, since it ends the task rather than running a step. The blank is
    // the first row a short pane gives up: kept, it would fold the list
    // below its least, or push the panel past a 15-row pane once a refusal
    // and a pinned `blocked` row are drawn as well.
    let least = match &picker.error {
        Some(_) => MIN_WINDOW + REFUSAL_LEAST,
        None => MIN_WINDOW,
    };
    let gap = picker.rows[picker.listed..]
        .iter()
        .any(|row| row.step == crate::pipeline::DONE)
        && height.is_none_or(|height| height.saturating_sub(fixed + 1) >= least);
    let fixed = fixed + usize::from(gap);
    let room = match height {
        Some(height) => {
            let free = height.saturating_sub(fixed);
            // The refusal takes what the list can spare above its own least,
            // but never less than its blank line and its first line.
            let keep = free
                .saturating_sub(MIN_WINDOW)
                .max(REFUSAL_LEAST)
                .min(error.len());
            if keep < error.len() {
                error.truncate(keep);
                if let Some(last) = error.last_mut() {
                    last.push_str(" …");
                }
            }
            free.saturating_sub(error.len())
        }
        None => usize::MAX,
    };
    let window = list_window(picker, room);

    let mut body = vec![String::new(), picker.header.clone()];
    body.extend(error);

    // The `▲`/`▼` lines sit among the answers, so the cursor's index into
    // them counts those lines to land on the cursor's own step. `ask` gives
    // them no `>` of their own: the cursor never rests on one.
    let mut answers = Vec::new();
    if window.marked && window.start > 0 {
        answers.push(format!("▲ {} more", window.start));
    }
    let listed_at = answers.len();
    answers.extend((window.start..window.start + window.shown).map(line));
    let below = picker.listed - window.start - window.shown;
    if window.marked && below > 0 {
        answers.push(format!("▼ {below} more"));
    }
    // A picker with no steps is a refusal opened by `Board::refuse_resume`:
    // there is nothing to pick and `enter` would resume nothing.
    if picker.rows.is_empty() {
        body.push(String::new());
        body.push(crate::screen::keys(&[("esc", "close")]));
        body.push(String::new());
        return crate::screen::boxed(&format!("resume {}", picker.name), &body);
    }
    let mut cursor_pinned = None;
    for i in picker.listed..picker.rows.len() {
        if gap && picker.rows[i].step == crate::pipeline::DONE {
            answers.push(String::new());
        }
        if i == picker.cursor {
            cursor_pinned = Some(answers.len());
        }
        answers.push(line(i));
    }
    let cursor = match cursor_pinned {
        Some(at) => at,
        None => picker
            .cursor
            .checked_sub(window.start)
            .filter(|at| *at < window.shown)
            .map_or(usize::MAX, |at| listed_at + at),
    };
    crate::screen::ask(&format!("resume {}", picker.name), &body, &answers, cursor)
}

/// The fewest rows a scrolled picker list is drawn in while it can still
/// say what it leaves out: `▲`, the cursor's own step, and `▼`.
const MIN_WINDOW: usize = 3;

/// The fewest rows a refusal is cut to: the blank line above it and its
/// first line.
const REFUSAL_LEAST: usize = 2;

/// The slice of the picker's listed steps [`list_window`] draws.
struct Window {
    start: usize,
    shown: usize,
    /// Whether the `▲`/`▼` lines are drawn for what the slice leaves out —
    /// `false` once the pane has room for one step and nothing more.
    marked: bool,
}

/// The slice of the picker's listed steps that fits in `room` rows — `room`
/// counting the `▲`/`▼` lines the slice needs for whatever it leaves out.
///
/// Centred on the cursor while it is on a listed step. On a pinned row it is
/// centred on the stopped step and its `on_pass` and `on_fail` targets
/// instead, so the list still shows where the task stopped and where it
/// would have gone. A window that reaches either end of the list needs no
/// line for that end, and takes the row back for one more step.
///
/// With fewer than [`MIN_WINDOW`] rows the list folds to its anchor alone,
/// with no `▲`/`▼` lines: the cursor's row, which the person is acting on,
/// is the one row never cut.
fn list_window(picker: &ResumePicker, room: usize) -> Window {
    let n = picker.listed;
    if n <= room {
        return Window {
            start: 0,
            shown: n,
            marked: false,
        };
    }
    let anchor = match picker.cursor < n {
        true => picker.cursor,
        false => picker
            .labelled
            .map_or(0, |(first, last)| (first + last) / 2),
    };
    if room < MIN_WINDOW {
        return Window {
            start: anchor,
            shown: 1,
            marked: false,
        };
    }
    let inner = room - 2;
    let start = anchor.saturating_sub(inner / 2).min(n - inner);
    let (start, shown) = if start == 0 {
        (0, room - 1)
    } else if start + inner == n {
        (n - (room - 1), room - 1)
    } else {
        (start, inner)
    };
    Window {
        start,
        shown,
        marked: true,
    }
}

/// [`BoardMode::ConfirmSkipHook`]'s panel: what skipping the failed hook
/// does, titled with the hook's event as a question.
///
/// A `done` hook's form says the task is archived and its worktree removed,
/// and that its ticket is left as it is. The ticket is named as `ticket:`
/// stores it, since spoolway never reads its state or labels from the
/// tracker; a task with no ticket gets no ticket line. A `queued` or
/// `started` hook's form names the step the task starts on instead. A
/// refusal, from opening the panel or from its answer, is printed under the
/// body, above the one answer.
pub(super) fn skip_hook_confirm_panel(confirm: &SkipHookConfirm) -> Vec<String> {
    use crate::commands::SkipThen;
    let id = &confirm.id;
    let (mut body, answer) = match &confirm.then {
        SkipThen::Archive { ticket } => {
            let mut body = vec![format!("{id} is archived and its worktree removed.")];
            if let Some(ticket) = ticket {
                body.push(format!("Ticket {ticket} stays as it is."));
            }
            (body, "skip and archive".to_string())
        }
        SkipThen::Start { entry } => (
            vec![format!(
                "{id} starts on {entry}, without its {} hook.",
                confirm.event
            )],
            format!("skip and start {entry}"),
        ),
    };
    if let Some(err) = &confirm.error {
        body.push(String::new());
        body.extend(
            err.lines()
                .flat_map(|l| crate::screen::wrap(l, crate::screen::NOTICE_WRAP)),
        );
    }
    crate::screen::ask(
        &format!("skip the {} hook?", confirm.event),
        &body,
        &[answer],
        0,
    )
}

/// [`BoardMode::ConfirmUnqueue`]'s panel. When `chain` names only the
/// cursor's own task it is a single sentence about that task: where in `dir`
/// it goes back to, or, for a routine copy the unqueue deletes, where its
/// routine stays. A longer chain lists its tasks in two groups, the ones going
/// back to `dir` and the routine copies being deleted, each dependent
/// annotated with what in the chain it depends on. A group with no members is
/// left out, its closing line with it.
///
/// The title names the head the way the board names its row, so a routine
/// copy reads as its routine whether it is deleted or not. In the body a
/// deleted copy is named by its routine too, and a task going to `dir` by its
/// id even when it is a copy whose routine is gone, since that id is the file
/// it lands under.
pub(super) fn unqueue_confirm_panel(chain: &[ChainEntry], dir: &std::path::Path) -> Vec<String> {
    let Some(head) = chain.first() else {
        return Vec::new();
    };
    let shown = |entry: &ChainEntry| match entry.routine_file {
        Some(_) => entry.name.clone(),
        None => entry.id.clone(),
    };
    if chain.len() == 1 {
        let body = match &head.routine_file {
            Some(routine_file) => vec![
                String::new(),
                "Nothing has run for it yet.".to_string(),
                String::new(),
                "This copy is deleted. The".to_string(),
                "routine stays in:".to_string(),
                shorten_home(routine_file),
                String::new(),
                "The routines tab queues it again.".to_string(),
            ],
            None => vec![
                String::new(),
                "Nothing has run for it yet.".to_string(),
                String::new(),
                "The task goes back to:".to_string(),
                shorten_home(&dir.join(format!("{}.md", head.id))),
                String::new(),
                "The queue tab is what sends it again.".to_string(),
            ],
        };
        return crate::screen::ask(
            &format!("unqueue {}", head.name),
            &body,
            &["unqueue it".to_string()],
            0,
        );
    }

    // A dependency is named the way its own line in the panel names it, so
    // the annotation can be matched to a line by eye.
    let line = |entry: &ChainEntry| {
        let name = shown(entry);
        if entry.depends_on.is_empty() {
            return format!("  {name}");
        }
        let depends_on: Vec<String> = entry
            .depends_on
            .iter()
            .map(|id| {
                chain
                    .iter()
                    .find(|e| &e.id == id)
                    .map_or_else(|| id.clone(), shown)
            })
            .collect();
        format!("  {name}{GUTTER}(depends on {})", depends_on.join(", "))
    };
    let (deleted, drafted): (Vec<&ChainEntry>, Vec<&ChainEntry>) =
        chain.iter().partition(|entry| entry.routine_file.is_some());

    let mut body = vec![String::new(), "Nothing has run for these yet.".to_string()];
    if !drafted.is_empty() {
        body.push(String::new());
        body.push(match drafted.len() {
            1 => "1 task goes back to:".to_string(),
            n => format!("{n} tasks go back to:"),
        });
        body.push(format!("{}/", shorten_home(dir)));
        body.push(String::new());
        body.extend(drafted.iter().map(|entry| line(entry)));
        body.push(String::new());
        body.push("The queue tab is what sends them again.".to_string());
    }
    if !deleted.is_empty() {
        body.push(String::new());
        body.push(match deleted.len() {
            1 => "1 routine copy is deleted:".to_string(),
            n => format!("{n} routine copies are deleted:"),
        });
        body.push(String::new());
        body.extend(deleted.iter().map(|entry| line(entry)));
        body.push(String::new());
        body.push("The routines tab queues them again.".to_string());
    }
    crate::screen::ask(
        &format!("unqueue {}", head.name),
        &body,
        &["unqueue them".to_string()],
        0,
    )
}

/// `path` with a leading run matching the home directory rewritten to `~`,
/// for the pending and routine paths an `unqueue` panel shows. A relative
/// path is returned as it is.
///
/// A small copy of `crate::repo::shorten_home`, which is private to that
/// module and outside what this task touches — duplicated here rather than
/// widened there, since the two callers want nothing else from each other.
fn shorten_home(path: &std::path::Path) -> String {
    let Some(home) = crate::platform::home_dir() else {
        return path.display().to_string();
    };
    match path.strip_prefix(&home) {
        Ok(rest) if rest.as_os_str().is_empty() => "~".to_string(),
        Ok(rest) => format!("~/{}", rest.display()),
        Err(_) => path.display().to_string(),
    }
}

/// What one agent profile has to show for this run: its name, its worker
/// slots and nothing else — the spend moved onto the board itself, as a
/// total line closing each group.
struct Spend {
    name: String,
    /// The profile's own figure — counted against the profile's own
    /// `concurrency` — drawn whether or not any of its steps also name a
    /// pooled model: a pool has its own cap, rationing the weights behind
    /// it, but the profile is still the thing `concurrency` rations, and a
    /// lane on a step naming no model counts against nothing else.
    own: String,
    /// One `(model, figure)` pair per pooled model this profile's steps
    /// name, each counted against that model's own `slots` — drawn on the
    /// same line as `own`, after it, in the order first seen. Empty for a
    /// profile whose steps name no pooled model.
    pools: Vec<(String, String)>,
}

/// One line per agent profile, its worker slots and nothing else — then, when
/// any job is enabled, the job ledger naming every one of them.
///
/// A line per profile rather than one summed line, because the two halves of a
/// run are not comparable: a cloud slot and a local one are not the same kind
/// of thing. A profile with a cap appears whether or not it has anything live
/// right now — its slots are worth reading empty. A profile with no cap at
/// all appears once it has a live lane, and not before: `codex` ships for the
/// sake of being pointed at, and a board nothing has been started on should
/// not carry an idle line about it.
///
/// `jobs` is `crate::jobs::active_jobs_cached`'s own answer, already ordered
/// by next firing — every enabled job gets one row under the whole slots
/// block, on every board with a row on it: the slot figures above answer
/// "what is spoolway running right now", and the ledger answers "what would
/// still bring it back to life" — the two things a person needs the
/// dispatcher resident to keep asking. Empty wherever no job is enabled,
/// which is when this draws nothing at all. An empty board draws no footer
/// at all, only the same ledger under its greeting while a dispatcher holds
/// the lock — see [`jobs_ledger`] and `paint_empty` in the parent module.
///
/// `waiting` is every pipeline file edited since the running dispatcher
/// started, then every config key whose new value it has not taken up — see
/// [`crate::pipeline_snapshot`]. Named on an `update` line under the slots,
/// since the run keeps routing on what it loaded and an edit waits for `u`.
/// Empty, and no line, otherwise.
///
/// `held` is how many slots `dispatch.priority = "reserve"` holds on each cap
/// for a started group. A figure with a hold on its cap reads
/// `<live>/<cap> · <n> held`, so a task waiting beside a free slot has its
/// reason on screen; a cap with none, and every cap under any other priority,
/// reads as it always has. A model's hold is on its own row's cap, so it
/// follows the model's figure and never the profile's.
///
/// Every argument is a distinct piece of state the reading took once —
/// bundling them into a struct only to pass one reference would hide that.
#[allow(clippy::too_many_arguments)]
pub(super) fn footer(
    repo: &Repo,
    pipelines: &Pipelines,
    used: &BTreeMap<&str, usize>,
    model_used: &BTreeMap<&str, usize>,
    agent_model: &BTreeMap<&str, Vec<&str>>,
    held: &BTreeMap<crate::dispatch::Cap, usize>,
    jobs: &[crate::jobs::ActiveJob],
    waiting: &[String],
) -> Vec<String> {
    // Which profiles this project could actually start a lane on. Config
    // ships a profile per agent kind spoolway can drive, so a project that
    // has never named `codex` in a pipeline still carries an `[agents.codex]`
    // section — and a cap written there is a fact about an account, not a
    // promise that anything here will ever use it. Reserving a slots line
    // for it puts a permanently `0/1` row on the board of every project that
    // does not run that kind.
    let runnable = pipelines.referenced_agents();
    let spends: Vec<Spend> = repo
        .config
        .agents
        .iter()
        .filter_map(|(name, profile)| {
            // Every model this profile's steps name that carries its own
            // `slots`, one entry per pool — but two names that match the same
            // `[models."<row>"]` entry collapse to the one entry, since they
            // are the same pool being rationed and must draw only one line.
            // `dispatch::slot_key` names the row `resolve` takes `slots` from
            // (through `models::row_setting`, the dispatcher's own key for
            // the pool), so comparing that row's *key* is comparing pool
            // identity as `resolve` sees it, even when a more literal row
            // sets other values: `ornith/Ornith-1.5-35B-A3B` and pi's own bare
            // `Ornith-1.5-35B-A3B` both key on `Ornith-1.5-35B-A3B` and
            // collapse to one line, which a raw glob match would miss since
            // it never takes the suffix fallback. The line is labelled by
            // `pool_label`, the rule a queued row's NEXT names the pool by.
            let spellings: &[&str] = agent_model.get(name.as_str()).map_or(&[], Vec::as_slice);
            let mut pools: Vec<(&str, u32, String)> = Vec::new();
            for model in spellings {
                let Some(slots) = crate::models::resolve(&repo.config.models, model)
                    .price
                    .filter(|p| p.slots > 0)
                    .map(|p| p.slots)
                else {
                    continue;
                };
                let key = crate::dispatch::slot_key(&repo.config.models, model);
                if pools.iter().any(|(_, _, seen)| *seen == key) {
                    continue;
                }
                let label = pool_label(&repo.config.models, spellings, &key).unwrap_or(model);
                pools.push((label, slots, key));
            }
            let live = used.get(name.as_str()).copied().unwrap_or(0);
            // Which profiles are worth a line. A cap is: one the profile
            // asserts, or one a model it names does. A profile with neither
            // is not hidden — it is only hidden when it also has nothing
            // live, which is what keeps the profiles that ship for the sake
            // of being pointed at off a board nothing has been started on.
            if profile.concurrency == 0 && pools.is_empty() && live == 0 {
                return None;
            }
            // A cap on a profile no step names rations nothing. The line
            // would read `0/1` for the life of the run and never move,
            // because no pipeline here can put a lane on it. A live lane
            // still earns a line whatever the pipelines say — a lane that
            // exists is one the board must account for, even if the step that
            // started it has since been edited away.
            if live == 0 && !runnable.contains_key(name.as_str()) {
                return None;
            }
            // `∞` rather than the profile's `0`: unlimited is what zero
            // means here, and printing `1/0` reads as a cap already
            // breached.
            let own = match profile.concurrency {
                0 => format!("{live}/∞"),
                cap => format!("{live}/{cap}"),
            };
            let own = own + &held_suffix(held, &crate::dispatch::Cap::Profile(name.clone()));
            // One line per profile, not one per pool: the un-pooled case
            // the mockup in `gh-378` draws (`pi` running one pooled lane and
            // one un-pooled one) needs both figures on the same row, or the
            // profile's own count reads as belonging to nothing. This used
            // to draw a separate line per pool instead, with the profile's
            // own figure dropped outright once any pool existed.
            let pools = pools
                .into_iter()
                .map(|(model, slots, key)| {
                    let live = model_used.get(model).copied().unwrap_or(0);
                    let cap = crate::dispatch::Cap::Model(key);
                    (
                        model.to_string(),
                        format!("{live}/{slots}{}", held_suffix(held, &cap)),
                    )
                })
                .collect();
            Some(Spend {
                name: name.clone(),
                own,
                pools,
            })
        })
        .collect();

    let width = |of: &dyn Fn(&Spend) -> usize| spends.iter().map(of).max().unwrap_or(0);
    // Widened to fit "jobs" too, but only when the ledger below actually
    // draws: a board with no enabled job never prints that label, and must
    // not pad every slot line for a column nothing here uses. When it does
    // draw, "jobs" shares this same column with every profile name — the
    // mockup's own alignment — so a project running only short names (`pi`,
    // four columns short of "jobs") still lines its ledger up under them.
    let name_w = {
        let profiles_w = width(&|s| s.name.chars().count());
        match jobs.is_empty() {
            true => profiles_w,
            false => profiles_w.max("jobs".chars().count()),
        }
    };

    // One rendered line per profile — its own figure, then every pool it
    // carries, model and figure, appended after it in the order first seen.
    let mut lines: Vec<String> = spends
        .iter()
        .map(|spend| {
            let pools: String = spend
                .pools
                .iter()
                .map(|(model, slots)| format!("{GUTTER}{model}{GUTTER}{slots}"))
                .collect();
            format!(
                "{BOLD}{name:<name_w$}{RESET}{GUTTER}{DIM}slots{RESET} {own}{pools}",
                name = spend.name,
                own = spend.own,
            )
        })
        .collect();

    // A person who edited a pipeline mid-run would otherwise watch the run
    // ignore the edit with nothing saying why. Not `GUTTER` after the label:
    // this line shares no column with the slots lines above it. The label is
    // padded to the width `pipelines` had when it labelled this line, so the
    // notice starts in the column a person already looks in.
    if let Some(notice) = update_notice(waiting) {
        lines.push(format!("{BOLD}update{RESET}     {notice}"));
    }

    // The job ledger, below the whole slots block: every enabled job, ordered
    // by next firing, naming what would still bring the dispatcher back to
    // life once nothing above it is running. Absent wherever no job is
    // enabled. Uses the same `name_w` the slots lines above align to, so
    // "jobs" and every profile name share one column.
    if !jobs.is_empty() {
        lines.push(String::new());
        lines.extend(jobs_ledger(jobs, name_w));
    }
    lines
}

/// The footer's `update` line about `waiting`, or `None` when nothing waits:
/// what changed, and the key on this board that brings it in.
fn update_notice(waiting: &[String]) -> Option<String> {
    if waiting.is_empty() {
        return None;
    }
    Some(format!(
        "{} changed since this run started — press u to update config",
        waiting.join(", ")
    ))
}

/// The name a footer line gives the pool behind `[models]` row `key`: the
/// first of a profile's `spellings` (its `agent_model` entry) whose model
/// has its own `slots` and resolves to that row. Two spellings of one row,
/// such as `qwen3` and `local/qwen3`, draw one figure, under whichever the
/// profile's steps named first.
///
/// One rule for the footer and for a queued row's NEXT, so a row kept out by
/// a hold on that pool names it as the footer does.
pub(super) fn pool_label<'m>(
    models: &BTreeMap<String, crate::usage::ModelPrice>,
    spellings: &[&'m str],
    key: &str,
) -> Option<&'m str> {
    spellings.iter().copied().find(|model| {
        crate::models::resolve(models, model)
            .price
            .is_some_and(|p| p.slots > 0)
            && crate::dispatch::slot_key(models, model) == key
    })
}

/// ` · <n> held` for a cap `reserve` holds `n` slots on, and nothing for one
/// it holds none on.
fn held_suffix(held: &BTreeMap<crate::dispatch::Cap, usize>, cap: &crate::dispatch::Cap) -> String {
    match held.get(cap).copied().unwrap_or(0) {
        0 => String::new(),
        n => format!(" · {n} held"),
    }
}

/// The job ledger: a `jobs   <n> active` line, then one
/// `○ <name>   <next firing>   (<until>)` line per job in `jobs`, in the
/// order given. Empty when `jobs` is.
///
/// One function for both boards that draw it — [`footer`] under the busy
/// board's slots lines, and [`greeting_screen`] under an idle dispatcher's
/// `Nothing queued` — so the two cannot word or order the ledger apart.
/// `name_w` is the column "jobs" is padded to, so the footer can line it up
/// with its profile names; it never pads to less than "jobs" itself, so the
/// empty board, which has no profile names, passes 0.
pub(super) fn jobs_ledger(jobs: &[crate::jobs::ActiveJob], name_w: usize) -> Vec<String> {
    if jobs.is_empty() {
        return Vec::new();
    }
    let name_w = name_w.max("jobs".chars().count());
    let mut lines = vec![format!(
        "{BOLD}{:<name_w$}{RESET}{GUTTER}{n} active",
        "jobs",
        n = jobs.len(),
    )];
    // Job names get their own column, separate from `name_w` above: a
    // routine's name has no reason to share a width with an agent
    // profile's, and the mockup this follows gives each block its own.
    let job_name_w = jobs
        .iter()
        .map(|j| j.name.chars().count())
        .max()
        .unwrap_or(0);
    let indent = format!("{:name_w$}{GUTTER}", "");
    let now = chrono::Local::now();
    for job in jobs {
        let when = match job.next {
            Some(at) => format!(
                "{}{GUTTER}({})",
                at.format("%a %-d %b %H:%M"),
                crate::jobs::until(at - now)
            ),
            // The same fact `doctor`'s own "schedule fires" check names —
            // a job whose expression parses but never comes round — kept
            // on the ledger rather than dropped, so a person still sees
            // it is there and broken.
            None => "will never fire — run `spoolway doctor`".to_string(),
        };
        lines.push(format!("{indent}○ {:<job_name_w$}{GUTTER}{when}", job.name,));
    }
    lines
}

/// How a table is dressed for whoever is reading it.
pub(super) struct Style {
    /// Colour is the board's, and the board's alone: `queue list` is piped
    /// into `grep` often enough that an escape code in the middle of a state
    /// word is a bug waiting to happen.
    colour: bool,
    /// The pane the table has to fit inside, when it has to fit inside one.
    /// The board redraws a fixed frame, so a row that wraps breaks every
    /// column under it; `queue list` prints once and scrolls, so it clips
    /// nothing and the reader keeps the whole blocker text.
    clip_to: Option<usize>,
    /// Whether CTX, OUT, COST, TIME and the per-group closing total lines
    /// are drawn at all. The board's own reading of the queue; `queue list`
    /// prints the band, TASK, PIPELINE, STEP, STATE and NEXT only — the same
    /// rows, the same grouping, none of the spend.
    figures: bool,
    /// Whether TASK draws a routine copy under its routine's name — see
    /// [`Row::name`]. The board's alone: `queue list` keeps the id, because
    /// what it prints is read back into `spoolway resume` and `grep`, and a
    /// routine's name is no task id either one could find.
    routine_names: bool,
}

impl Style {
    pub(super) fn board(pane: usize) -> Style {
        Style {
            colour: true,
            clip_to: Some(pane),
            figures: true,
            routine_names: true,
        }
    }

    fn plain() -> Style {
        Style {
            colour: false,
            clip_to: None,
            figures: false,
            routine_names: false,
        }
    }

    /// What `row`'s TASK cell reads in this style.
    fn task_name<'a>(&self, row: &'a Row) -> &'a str {
        match self.routine_names {
            true => row.name(),
            false => &row.id,
        }
    }

    fn paint(&self, colour: &str, text: &str) -> String {
        match self.colour {
            true => format!("{colour}{text}{RESET}"),
            false => text.to_string(),
        }
    }
}

/// What one group has banked: every ledger entry for a task the board is
/// drawing, grouped by the ledger's own `plan` field, which carries a task's
/// `group:` verbatim. A row's OUT, COST and TIME are the step it is on; a
/// total is what the group has already banked — every settled step, every
/// round it ran, whether or not its task has since reached `done`. The ledger
/// only ever gains a line once a lane settles (see the module doc on
/// `usage.rs`), so every entry here is already banked spend, never a running
/// step's live figures.
///
/// A total used to add each row's unbanked spend on top so it could never
/// read smaller than the running row printed above it, and that made it a
/// second copy of that row, climbing in step with it. A total is for
/// watching a group's bill accumulate as steps settle, so it may well read
/// lower than the row above it, and a group with nothing banked has no
/// figures at all.
pub(super) struct GroupTotal {
    out: Option<u64>,
    cost: Option<f64>,
    lane_time: Option<i64>,
}

/// Every group with a banked step on the board, summed. Groups with nothing
/// banked — including one whose lanes are all still running — simply have no
/// total to print, which [`table`] reads the same as any other empty figure.
pub(super) fn group_totals(
    ledger: &crate::usage::LedgerTotals,
    rows: &[Row],
) -> BTreeMap<String, GroupTotal> {
    // The tasks the board is drawing at all — its live queue plus the
    // archived rows beside it. Spend banked for a task not here belongs to
    // no row this board prints, so it is not this board's business either.
    let visible: BTreeSet<&str> = rows.iter().map(|row| row.id.as_str()).collect();
    let mut totals: BTreeMap<String, GroupTotal> = BTreeMap::new();
    // The ledger's own `plan` field carries a task's `group:` verbatim. A
    // command step's run is not counted: its wall time is a gate's, and a
    // group's TIME is what its lanes were busy. A line only exists once its
    // lane has settled — see [`GroupTotal`] — so the one thing left to rule
    // out is a task this board is not drawing at all.
    for (task, group, spend) in ledger.groups() {
        if !visible.contains(task) {
            continue;
        }
        let total = totals.entry(group.to_string()).or_insert(GroupTotal {
            out: Some(0),
            cost: None,
            lane_time: Some(0),
        });
        total.out = total.out.map(|out| out + spend.output);
        total.lane_time = total.lane_time.map(|wall| wall + spend.wall_s);
        if let Some(usd) = spend.cost_usd {
            *total.cost.get_or_insert(0.0) += usd;
        }
    }
    totals
}

/// Below this many arrivals the count is not yet worth a reader's notice, so
/// the step id stays bare.
const ARRIVAL_FLOOR: u32 = 2;

/// The STEP column's counter suffix, on its own — `None` below
/// [`ARRIVAL_FLOOR`]. The one place the threshold and the ` ↻ <n>` spelling
/// are written, so `step_text` and `table`'s painted branch can never drift
/// onto different text for the same row.
fn arrival_suffix(arrivals: u32) -> Option<String> {
    (arrivals >= ARRIVAL_FLOOR).then(|| format!(" ↻ {arrivals}"))
}

/// The STEP column's plain text, counter included where there is one — the
/// same string whether or not it ends up painted, so a width computed from it
/// and a cell padded against it always agree.
fn step_text(row: &Row) -> String {
    match arrival_suffix(row.arrivals) {
        Some(suffix) => format!("{}{suffix}", row.stage),
        None => row.stage.clone(),
    }
}

/// The floor `TASK` clips toward before any figure column sheds. See
/// [`table`]'s width computation for the order the moves happen in.
const ID_FLOOR: usize = 14;

/// How far `TASK` may shrink past `ID_FLOOR` as a last resort, for a pane the
/// floor alone cannot fit into. The header word's own literal width —
/// `"TASK"`, four characters — because padding never truncates, so a column
/// wanted any narrower would not actually be: the header text would simply
/// overhang whatever width was asked for.
const ID_MIN: usize = 4;

/// The task table, grouped by group — the board's and `queue list`'s one and
/// only renderer.
///
/// Two readings of one queue that disagreed about anything but colour would be
/// two answers to "where is everything", so there is one function and the
/// difference is a [`Style`].
pub(super) fn table(
    rows: &[Row],
    style: Style,
    totals: &BTreeMap<String, GroupTotal>,
    cursor: Option<&str>,
) -> String {
    table_laid_out(rows, style, totals, cursor).0
}

/// Where [`table`]'s lines sit: the line each task row is drawn on, and the
/// line of the band over its group. Counted from the column header, line 0.
///
/// Only the board reads it, to scroll a table taller than its pane — see
/// [`table_window`]. A band is `None` for a row in the `no group` block,
/// which draws none.
#[derive(Debug, Default)]
pub(super) struct TableLayout {
    /// One entry per row of the table's `rows`, in the same order.
    pub(super) tasks: Vec<usize>,
    /// The band line over each entry of `tasks`.
    pub(super) bands: Vec<Option<usize>>,
}

/// [`table`], with the [`TableLayout`] of what it drew. The layout is noted
/// in the same loop that pushes each line, so it cannot fall out of step
/// with a band or a total line the table draws or leaves off.
pub(super) fn table_laid_out(
    rows: &[Row],
    style: Style,
    totals: &BTreeMap<String, GroupTotal>,
    cursor: Option<&str>,
) -> (String, TableLayout) {
    let width = |of: &dyn Fn(&Row) -> usize, header: usize| {
        rows.iter().map(of).max().unwrap_or(0).max(header)
    };
    let total_width =
        |of: &dyn Fn(&GroupTotal) -> usize| totals.values().map(of).max().unwrap_or(0);

    let id_w_natural = width(&|r| style.task_name(r).chars().count(), 4);
    // "PIPELINE", 8 characters — the widest thing in the column on almost
    // every board, since a project's pipeline names are usually shorter than
    // the header naming them.
    let pipeline_w = width(&|r| r.pipeline.chars().count(), 8);
    // Two widths: the bare step id, and the id with its `↻ <n>` counter where
    // a row has one. `show_loop`, below, decides which the column actually
    // draws at any given pane width — narrow enough and the counter goes,
    // same as any other shed column, and STEP returns to `step_w_bare`.
    let step_w_bare = width(&|r| r.stage.chars().count(), 4);
    let step_w_loop = width(&|r| step_text(r).chars().count(), 4);
    // Wide enough for the widest state *on the board*, and no wider. Sized to
    // the widest word there is instead, a queue of running tasks holds seven
    // columns open for a state nothing is in.
    let state_w = width(&|r| state_cell_text(r).chars().count(), 5);
    let ctx_w = width(
        &|r| figure(r.ctx.map(|pct| format!("{pct}%"))).chars().count(),
        3,
    );
    // Each figure column is sized against the rows *and* the total lines
    // that close each group — a group's whole spend can easily run wider than
    // any one step's.
    let out_w = width(&|r| figure(r.out.map(tokens_k)).chars().count(), 3).max(total_width(&|t| {
        figure(t.out.map(tokens_k)).chars().count()
    }));
    let cost_w = width(
        &|r| {
            figure(r.cost.map(|usd| crate::fmt::money(Some(usd))))
                .chars()
                .count()
        },
        4,
    )
    .max(total_width(&|t| {
        figure(t.cost.map(|usd| crate::fmt::money(Some(usd))))
            .chars()
            .count()
    }));
    let time_w =
        width(&|r| figure(r.lane_time.map(human_secs)).chars().count(), 4).max(total_width(&|t| {
            figure(t.lane_time.map(human_secs)).chars().count()
        }));

    // Every line carries the frame's one-column margin — the header, a
    // task row, a band and a group's closing total line alike.
    let lead = MARGIN;

    // How wide TASK gets to be. `queue list` (no `clip_to`) never narrows
    // it — it keeps every column at every width, unclipped, because it is
    // piped into `grep` far too often for an ellipsis to be safe.
    let mut id_w = id_w_natural;
    // Shown whenever there is room, on both readings of the table: like
    // `show_next`, not gated on `style.figures` — a loop count is not a spend
    // figure. `queue list` never clips at all, so this never leaves it there.
    let mut show_loop = true;
    let mut show_ctx = style.figures;
    let mut show_out = style.figures;
    let mut show_cost = style.figures;
    let mut show_time = style.figures;
    let mut show_next = true;
    // Never gated on `style.figures`, the same as `show_next`: PIPELINE is
    // not one of the spend columns, so both readings of the table carry it
    // right up until a narrow pane sheds it.
    let mut show_pipeline = true;

    // The gap between TASK and STEP: `GUTTER`, the column, `GUTTER` while
    // PIPELINE is on the row, or `TASK_GAP` alone once it has shed — the gap
    // that boundary carried before this column existed. Read by `fits` for
    // every width the row is a candidate at, so it takes `show_pipeline`
    // rather than closing over the outer one.
    let task_step_gap = |show_pipeline: bool| -> usize {
        match show_pipeline {
            true => GUTTER.len() + pipeline_w + GUTTER.len(),
            false => TASK_GAP.len(),
        }
    };

    if let Some(pane) = style.clip_to {
        // Whether the row fits, given NEXT gets at least the width of its
        // own header once shown. `clip` would draw a cell in one character,
        // but the header row spells `NEXT` out whole, so a pane with room
        // for one character more than the rest would push that row past
        // the pane's edge. A `show_next` this test passed under never
        // overflows once the real room (usually far more) is handed to it
        // below.
        let fits = |id_w: usize,
                    show_loop: bool,
                    show_pipeline: bool,
                    show_ctx: bool,
                    show_out: bool,
                    show_cost: bool,
                    show_time: bool,
                    show_next: bool|
         -> bool {
            let step_w = match show_loop {
                true => step_w_loop,
                false => step_w_bare,
            };
            let mut w = lead.len()
                + CURSOR_GUTTER_WIDTH
                + id_w
                + task_step_gap(show_pipeline)
                + step_w
                + GUTTER.len()
                + state_w;
            if show_ctx {
                w += GUTTER.len() + ctx_w;
            }
            if show_out {
                w += GUTTER.len() + out_w;
            }
            if show_cost {
                w += GUTTER.len() + cost_w;
            }
            if show_time {
                w += GUTTER.len() + time_w;
            }
            if show_next {
                w += GUTTER.len() + "NEXT".len();
            }
            w <= pane
        };

        // Three moves, in this order: the loop counter goes first, before
        // TASK gives up a single character — a reader can lose the lap count
        // and still read every row, but a clipped id is a worse trade for
        // the same room. Only once the counter is gone does TASK clip toward
        // `ID_FLOOR`, and only once it is there does a figure column go,
        // right to left across the row: NEXT, then PIPELINE, then TIME,
        // COST, OUT, CTX. Stops the moment the row fits, so a pane just
        // short of the natural width loses only a character or two rather
        // than a whole column.
        //
        // PIPELINE right after NEXT rather than beside the spend figures: it
        // is not one of them, and dropping it is what lets the six-space
        // `TASK_GAP` stand between TASK and STEP again — see
        // [`task_step_gap`] — so a board without the column reads exactly as
        // one that never gained it.
        //
        // Below the floor is the last resort, for a pane the floor alone
        // cannot fit into: the row stays one line rather than the floor
        // being honoured into a wrap. It stops at `ID_MIN` — the header
        // word's own literal width — because a column narrower than its own
        // header word is not narrower on screen at all: `format!("{:<w$}",
        // "TASK")` pads a short width, it never truncates a longer word to
        // fit it.
        loop {
            if fits(
                id_w,
                show_loop,
                show_pipeline,
                show_ctx,
                show_out,
                show_cost,
                show_time,
                show_next,
            ) {
                break;
            }
            if show_loop {
                show_loop = false;
            } else if id_w > ID_FLOOR {
                id_w -= 1;
            } else if show_next {
                show_next = false;
            } else if show_pipeline {
                show_pipeline = false;
            } else if show_time {
                show_time = false;
            } else if show_cost {
                show_cost = false;
            } else if show_out {
                show_out = false;
            } else if show_ctx {
                show_ctx = false;
            } else if id_w > ID_MIN {
                id_w -= 1;
            } else {
                break;
            }
        }
    }

    // The width STEP actually draws at, settled by `show_loop` above: with
    // no `clip_to` at all (`queue list`) the shedding loop never runs and
    // `show_loop` stays `true`, so this is always `step_w_loop` there — the
    // counter draws at every width, exactly as `plain_table` promises.
    let step_w = match show_loop {
        true => step_w_loop,
        false => step_w_bare,
    };

    // How much of the line the shown figure columns and their gutters take,
    // so NEXT — the only column with no width of its own — knows what room
    // is left for it.
    let tail_width = (if show_ctx { GUTTER.len() + ctx_w } else { 0 })
        + (if show_out { GUTTER.len() + out_w } else { 0 })
        + (if show_cost { GUTTER.len() + cost_w } else { 0 })
        + (if show_time { GUTTER.len() + time_w } else { 0 });
    // The cursor gutter through STATE, PIPELINE included wherever it is
    // still shown — shared by `columns`, below, and by `total_span`, since
    // both are the same span measured to a different point along the row.
    let head_width =
        CURSOR_GUTTER_WIDTH + id_w + task_step_gap(show_pipeline) + step_w + GUTTER.len() + state_w;
    let columns = lead.len() + head_width + tail_width + if show_next { GUTTER.len() } else { 0 };

    // How far the closing total line runs blank before its first figure:
    // everything from TASK up to and including CTX, where CTX is still on
    // the board at all. Measured from TASK rather than from the gutter,
    // since the gutter is printed on its own — see `close_group`, below —
    // the same as every row's.
    let total_span = id_w
        + task_step_gap(show_pipeline)
        + step_w
        + GUTTER.len()
        + state_w
        + if show_ctx { GUTTER.len() + ctx_w } else { 0 };

    // A shown cell, gutter included — `None` where the column has shed, so
    // the caller drops it whole rather than leaving a gutter with nothing
    // after it.
    let cell_opt = |shown: bool, text: String| -> Option<String> { shown.then_some(text) };
    let tail = |cells: [Option<String>; 4]| -> String {
        let mut out = String::new();
        for cell in cells.into_iter().flatten() {
            out.push_str(GUTTER);
            out.push_str(&cell);
        }
        out
    };

    let mut out = String::new();
    // One shape for both readings: PIPELINE and NEXT are gated on
    // `show_pipeline`/`show_next` alone, not on `style.figures` — only the
    // spend figures between STATE and NEXT are `style.figures`'s to show.
    let mut header = format!("{lead}{NO_CURSOR}{:<id_w$}", "TASK");
    match show_pipeline {
        true => {
            header.push_str(GUTTER);
            header.push_str(&format!("{:<pipeline_w$}", "PIPELINE"));
            header.push_str(GUTTER);
        }
        false => header.push_str(TASK_GAP),
    }
    header.push_str(&format!("{:<step_w$}{GUTTER}{:<state_w$}", "STEP", "STATE"));
    if style.figures {
        header.push_str(&tail([
            cell_opt(show_ctx, format!("{:>ctx_w$}", "CTX")),
            cell_opt(show_out, format!("{:>out_w$}", "OUT")),
            cell_opt(show_cost, format!("{:>cost_w$}", "COST")),
            cell_opt(show_time, format!("{:>time_w$}", "TIME")),
        ]));
    }
    if show_next {
        header.push_str(GUTTER);
        header.push_str("NEXT");
    }
    out.push_str(&style.paint(DIM, &header));
    out.push('\n');

    // The band that opens a group's block: `▌<group>`, at the margin itself —
    // outdented past the cursor gutter every row carries, so it reads as a
    // heading rather than a row of its own. Drawn for both readings of the
    // table, figures or none. Nothing for the `no group` block — there is no
    // name for it to carry.
    let band = |out: &mut String, group: &str, url: Option<&str>, after: Option<&str>| {
        if group == NO_GROUP {
            return;
        }
        // Compose the visible line as plain text first — this is the string a
        // width measurement or a clip would act on, the same compose-then-
        // colour order the rest of this function keeps, and `ticker` too.
        // The band itself is never clipped: its full
        // name shows at every pane width, see
        // `a_narrow_pane_sheds_columns_and_clips_ids_before_a_row_wraps`.
        let plain = format!("{lead}▌{group}");
        // Only now, with the visible line whole, wrap the group-name span —
        // and only that span, leaving the `lead` and the `▌` outside it — in
        // an OSC 8 hyperlink to the group's issue. Only where the board
        // paints colour: a `queue list` piped to a file or a pager has no
        // terminal to resolve a link against. `plain` ends with `group`
        // verbatim, so the byte length of everything before it is a char
        // boundary.
        let mut composed = match url.filter(|_| style.colour) {
            Some(url) => {
                let before = &plain[..plain.len() - group.len()];
                format!("{before}{OSC8}{url}{ST}{group}{OSC8}{ST}")
            }
            None => plain,
        };
        // `after <group>` names the one other group this group's first task
        // stacks onto — see `Row::after`. Outside any hyperlink span, plain
        // words beside the band's own name rather than a second link.
        if let Some(after) = after {
            composed.push_str(&format!("  after {after}"));
        }
        out.push_str(&style.paint(DIM, &composed));
        out.push('\n');
    };

    // The total line closing the group's block: that group's whole OUT, COST
    // and TIME, aligned under whichever of those columns the rows are still
    // showing — the block sheds exactly what the rows shed. No label and no
    // counter, only blank space up to the figures: the sums under their own
    // columns are enough to say what the line is. Nothing where there is no
    // group to close — the `no group` group has nothing for the ledger to
    // have grouped by — and nothing where the style has no figures to show
    // at all. Nothing, either, on a board narrow enough to have shed every
    // figure column: with no label left to carry, the line would be blank.
    let close_group = |out: &mut String, group: &str| {
        if !style.figures || group == NO_GROUP {
            return;
        }
        if !(show_out || show_cost || show_time) {
            return;
        }
        let total_spend = totals.get(group);
        let out_fig = figure(total_spend.and_then(|t| t.out).map(tokens_k));
        let cost_fig = figure(
            total_spend
                .and_then(|t| t.cost)
                .map(|usd| crate::fmt::money(Some(usd))),
        );
        let time_fig = figure(total_spend.and_then(|t| t.lane_time).map(human_secs));
        let label = " ".repeat(total_span);
        let mut line = format!("{lead}{NO_CURSOR}{label}");
        line.push_str(&tail([
            None,
            cell_opt(
                show_out,
                pad(&style.dim_nothing(&out_fig), &out_fig, out_w, true),
            ),
            cell_opt(
                show_cost,
                pad(&style.dim_nothing(&cost_fig), &cost_fig, cost_w, true),
            ),
            cell_opt(
                show_time,
                pad(&style.dim_nothing(&time_fig), &time_fig, time_w, true),
            ),
        ]));
        line.push('\n');
        out.push_str(&line);
    };

    // The band's hyperlink target for a group is the first `url:` any of its
    // rows carries. `url:` is stored per task and is optional — a leading
    // task queued or archived before the tracker ran has none — so reading
    // only the first row would let that task hide a sibling's valid link.
    // `key-in-names` writes the same issue's url onto every task of a group
    // it opens, so the first one found stands for the whole group.
    let mut group_urls: BTreeMap<&str, &str> = BTreeMap::new();
    // The other group a group's own band names, `after <group>` — the first
    // task's own cross-group `depends_on`, stamped only on that one row (see
    // `Row::after`), so the first row of the group to carry one stands for
    // the whole band, the same way `group_urls` reads its first `issue_url`.
    let mut group_after: BTreeMap<&str, &str> = BTreeMap::new();
    for row in rows {
        if let Some(url) = row.issue_url.as_deref() {
            group_urls.entry(row.group()).or_insert(url);
        }
        if let Some(after) = row.after.as_deref() {
            group_after.entry(row.group()).or_insert(after);
        }
    }

    // Every line `out` holds ends in a newline, so the count of them is the
    // index the next line pushed will have.
    let next_line = |out: &str| out.matches('\n').count();
    let mut layout = TableLayout::default();
    let mut band_line: Option<usize> = None;
    let mut group: Option<&str> = None;
    for row in rows {
        if group != Some(row.group()) {
            if let Some(prev) = group {
                close_group(&mut out, prev);
            }
            group = Some(row.group());
            out.push('\n');
            band_line = (row.group() != NO_GROUP).then(|| next_line(&out));
            band(
                &mut out,
                group.unwrap(),
                group_urls.get(group.unwrap()).copied(),
                group_after.get(group.unwrap()).copied(),
            );
        }

        // A cell padded to its column and, for an archived row, dimmed whole
        // — `● done` reads as history next to rows still in play.
        let cell = |text: &str, width: usize| -> String {
            let padded = pad(text, text, width, false);
            match row.state == State::Done {
                true => style.paint(DIM, &padded),
                false => padded,
            }
        };
        let id_text = clip(style.task_name(row), id_w);
        let id_cell = cell(&id_text, id_w);
        // Always dim, on the board and nowhere else — the same `paint` every
        // other plain-text cell uses, just never conditioned on the row's
        // own state the way `cell` dims a `Done` row whole: PIPELINE reads
        // the same whether the task is running or archived, because the dim
        // is what separates the column from TASK and STEP beside it, not a
        // comment on the row.
        let pipeline_cell = pad(
            &style.paint(DIM, &row.pipeline),
            &row.pipeline,
            pipeline_w,
            false,
        );
        // The counter draws `DIM` in every case — the step id itself is
        // never dimmed, only the `↻ <n>` beside it is, and nothing about the
        // count is coloured since it reads against no ceiling. Gone whole
        // once `show_loop` has shed, so the column reads exactly as it did
        // before the counter existed. A `Done` row skips this and takes the
        // whole-cell dim every other archived column gets instead — history
        // reads as one dim block, not a step id at one weight next to a
        // counter at another.
        let step_plain = match show_loop {
            true => step_text(row),
            false => row.stage.clone(),
        };
        let step_cell = match row.state == State::Done {
            true => cell(&step_plain, step_w),
            false => {
                let painted = match show_loop.then(|| arrival_suffix(row.arrivals)).flatten() {
                    Some(suffix) => format!("{}{}", row.stage, style.paint(DIM, &suffix)),
                    None => row.stage.clone(),
                };
                pad(&painted, &step_plain, step_w, false)
            }
        };

        // The state and the figures carry invisible escape codes, so each is
        // padded by its visible characters — counted, not measured in bytes,
        // or the three-byte `●` shifts every row two columns out.
        let state = pad(
            &style.paint_state(row),
            &state_cell_text(row),
            state_w,
            false,
        );
        let ctx = figure(row.ctx.map(|pct| format!("{pct}%")));
        let out_tokens = figure(row.out.map(tokens_k));
        let cost = figure(row.cost.map(|usd| crate::fmt::money(Some(usd))));
        let lane_time = figure(row.lane_time.map(human_secs));

        // The cursor gutter carries the mark on the row it sits on and its
        // own blank everywhere else — see [`CURSOR_GUTTER_WIDTH`] — so a
        // highlighted row costs the rest of the line nothing: every column
        // still starts in the same place it would without a cursor on the
        // board at all.
        let cursor_gutter = match cursor == Some(row.id.as_str()) {
            true => CURSOR_MARK,
            false => NO_CURSOR,
        };
        let mut line = format!("{lead}{cursor_gutter}{id_cell}");
        match show_pipeline {
            true => {
                line.push_str(GUTTER);
                line.push_str(&pipeline_cell);
                line.push_str(GUTTER);
            }
            false => line.push_str(TASK_GAP),
        }
        line.push_str(&step_cell);
        line.push_str(GUTTER);
        line.push_str(&state);
        line.push_str(&tail([
            cell_opt(show_ctx, pad(&style.dim_nothing(&ctx), &ctx, ctx_w, true)),
            cell_opt(
                show_out,
                pad(&style.dim_nothing(&out_tokens), &out_tokens, out_w, true),
            ),
            cell_opt(
                show_cost,
                pad(&style.dim_nothing(&cost), &cost, cost_w, true),
            ),
            cell_opt(
                show_time,
                pad(&style.dim_nothing(&lane_time), &lane_time, time_w, true),
            ),
        ]));

        if show_next {
            let next = match style.clip_to {
                Some(pane) => clip(&row.next, pane.saturating_sub(columns)),
                None => row.next.clone(),
            };
            let next = match row.state {
                State::Done => style.paint(DIM, &next),
                _ => next,
            };
            line.push_str(GUTTER);
            line.push_str(&next);
        }
        line.push('\n');
        layout.tasks.push(next_line(&out));
        layout.bands.push(band_line);
        out.push_str(&line);
    }
    if let Some(last) = group {
        close_group(&mut out, last);
    }
    (out, layout)
}

/// [`table`]'s lines cut to its column header and the `rows` under it, for a
/// board whose table is taller than the rows its pane leaves the table.
///
/// A table that fits is drawn whole. One that does not keeps its header and
/// scrolls the rest under the cursor, `cursor` being an index into
/// `layout.tasks`: the view ends on the cursor's task, and on the total line
/// closing its group when it is the group's last task and the view has room
/// for its band as well, so the foot of a group reads whole once the cursor
/// reaches it. The view is worked out from the
/// cursor alone every frame — see [`crate::screen::pane::offset`] — so a group
/// that finishes between frames never leaves a stale scroll position behind.
///
/// The last of the `rows` is the marker, in the queue screen's words — see
/// [`crate::screen::pane::marker_row`] — counting task rows only: a band, a
/// total line or a blank row out of view is never counted. When no task is
/// out of view the marker row is not drawn and the table takes that row back.
///
/// When the view starts on a task or a total line below its own group's
/// band, the band is drawn on the view's first row in that line's place, so
/// every task row and total line drawn has its group named over it. A task
/// the band covers counts as above. The cursor
/// never sits on the pinned band: the view's first row is never the cursor's
/// own unless the view is too short to hold anything else, and then nothing
/// is pinned.
pub(super) fn table_window(
    table: &str,
    layout: &TableLayout,
    cursor: Option<usize>,
    rows: usize,
    pane: usize,
) -> Vec<String> {
    let lines: Vec<String> = table.lines().map(str::to_string).collect();
    let Some((header, body)) = lines.split_first() else {
        return lines;
    };
    let mut shown = vec![header.clone()];
    if body.len() <= rows {
        shown.extend_from_slice(body);
        return shown;
    }
    if rows == 0 {
        return shown;
    }
    // The layout counts the header as line 0; the body starts under it.
    let tasks: Vec<usize> = layout.tasks.iter().map(|line| line - 1).collect();
    let bands: Vec<Option<usize>> = layout
        .bands
        .iter()
        .map(|band| band.map(|line| line - 1))
        .collect();
    // The lines a view `view` lines tall keeps in sight.
    let focus = |view: usize| match tasks.get(cursor.unwrap_or(0)) {
        Some(&line) => {
            // A non-blank line under a task that is not itself a task is the
            // total line closing the group the task is last in. It joins the
            // focus only in a view with a row left above both for the band:
            // two rows of task and total would leave the task unnamed.
            let closes = view > 2
                && body
                    .get(line + 1)
                    .is_some_and(|next| !next.is_empty() && !tasks.contains(&(line + 1)));
            (line, line + usize::from(closes))
        }
        None => (0, 0),
    };
    // Each task is one line here, so a task is out of view exactly when its
    // own line is. `hidden_items` is not used: it runs a task on to the last
    // non-blank line before the next one, which on the board is the total
    // line and the next group's band, and would call a group's last task
    // below while its own row is still on screen.
    let count = |top: usize, bottom: usize| {
        let above = tasks.iter().filter(|&&line| line < top).count();
        let below = tasks.iter().filter(|&&line| line >= bottom).count();
        (above, below)
    };

    let view = rows - 1;
    let top = crate::screen::pane::offset(body.len(), view, focus(view));
    let mut window = body[top..top + view].to_vec();
    let mut first_shown = top;
    // The band of the group whose block the view's first row sits in: a
    // task's own, or, for the total line closing a group, its last task's.
    // A blank row belongs to no group, and the band under it comes next.
    let group_band = |line: usize| {
        let k = tasks.iter().rposition(|&task| task <= line)?;
        let in_block = tasks[k] == line || (tasks[k] + 1 == line && !body[line].is_empty());
        in_block.then_some(bands[k]).flatten()
    };
    let pinned = group_band(top).filter(|&band| band < top && top < focus(view).0);
    if let (Some(band), Some(first)) = (pinned, window.first_mut()) {
        *first = body[band].clone();
        first_shown = top + 1;
    }
    let (above, below) = count(first_shown, top + view);
    if above == 0 && below == 0 {
        // Only blank rows or a total line were out of view: a `rows`-line
        // view holds every one of them the shorter view did, and the row the
        // marker would have taken goes back to the table.
        let top = crate::screen::pane::offset(body.len(), rows, focus(rows));
        shown.extend_from_slice(&body[top..top + rows]);
        return shown;
    }
    let room = pane.saturating_sub(MARGIN.len() + CURSOR_GUTTER_WIDTH);
    let marker = crate::screen::pane::marker_row(above, below, "task", room);
    shown.extend(window);
    shown.push(format!("{MARGIN}{NO_CURSOR}{marker}"));
    shown
}

/// The full text of a row's STATE cell: the state's own word, and for a
/// `Silent` row how long the lane has been silent after it, in
/// [`state_age`]'s clock — `● silent · 31m`. A running hidden command step
/// draws how long its run has gone instead, in [`human_secs`]'s —
/// `● running 9m 12s`. Kept as its own function, rather than a direct call
/// to [`State::word`] at each of its call sites, for the plain-text and
/// coloured cells to stay the same shape.
fn state_cell_text(row: &Row) -> String {
    format!("{}{}", row.state.word(), state_suffix(row))
}

/// What a STATE cell draws after the state's word: ` · <time>` on a
/// `Silent` row, ` <time>` on a `Running` row with [`Row::hidden_run`] set,
/// nothing on any other. Drawn uncoloured, so the word alone carries the
/// state's colour as it does on every other row.
///
/// A hidden run's time is the TIME column's own figure, drawn in the same
/// [`human_secs`] clock, so the two cells of one row always agree. It is the
/// clock the restart panel shows a command's run in too. Asked of `Running`
/// alone, so a row [`super::finish_settled`] has since called finished draws
/// no time.
fn state_suffix(row: &Row) -> String {
    match (row.state, row.hidden_run) {
        (State::Silent { secs }, _) => format!(" · {}", state_age(secs)),
        (State::Running, Some(ran)) => format!(" {}", human_secs(ran)),
        _ => String::new(),
    }
}

/// An age drawn in the STATE column: seconds under a minute, whole minutes
/// under an hour, then hours and minutes — `42s`, `31m`, `1h 04m`. Coarser
/// than [`human_secs`] below the hour on purpose: an age in the STATE column
/// is read at a glance, not timed, so it keeps the whole-minute shape the
/// board's ages are drawn in rather than the TIME column's seconds.
fn state_age(total: i64) -> String {
    let (h, m, s) = (total / 3600, (total % 3600) / 60, total % 60);
    match (h, m) {
        (0, 0) => format!("{s}s"),
        (0, _) => format!("{m}m"),
        _ => format!("{h}h {m:02}m"),
    }
}

impl Style {
    fn paint_state(&self, row: &Row) -> String {
        match self.colour {
            true => format!("{}{}", row.state.dot(), state_suffix(row)),
            false => state_cell_text(row),
        }
    }

    /// A missing figure is dimmed, a present one is left alone: what the eye
    /// should skip is the dash.
    fn dim_nothing(&self, figure: &str) -> String {
        match figure == NOTHING {
            true => self.paint(DIM, figure),
            false => figure.to_string(),
        }
    }
}

/// A figure, or the mark that says there is none.
fn figure(value: Option<String>) -> String {
    value.unwrap_or_else(|| NOTHING.to_string())
}

/// `painted` padded to `width` by the visible width of `plain`, which is the
/// same text without whatever escape codes were wrapped around it.
fn pad(painted: &str, plain: &str, width: usize, right: bool) -> String {
    let room = " ".repeat(width.saturating_sub(plain.chars().count()));
    match right {
        true => format!("{room}{painted}"),
        false => format!("{painted}{room}"),
    }
}

/// The task table as `spoolway queue list` prints it: the same grouping, the
/// same widths, the same wording, in plain text and never clipped.
pub fn plain_table(rows: &[Row]) -> String {
    table(rows, Style::plain(), &BTreeMap::new(), None)
}

/// A token count at a glance: `840`, `140k`, `1.2M`.
///
/// Coarser than `spoolway eval`'s columns, which keep a decimal on the
/// thousands. A footer figure that ticks over while you watch it wants the
/// magnitude and nothing more — `139.7k` reads as precision that the next
/// finished lane immediately spends.
fn tokens_k(n: u64) -> String {
    match n {
        n if n < 1_000 => n.to_string(),
        n if n < 1_000_000 => format!("{}k", n / 1_000),
        n => format!("{:.1}M", n as f64 / 1_000_000.0),
    }
}

/// The lockup and one line of prose beside it, laid out for a pane this wide.
///
/// Side by side while both fit, because that is the design. What a narrow pane
/// must not do is wrap: the header runs under the lockup's second line and
/// pushes the two below it down a row, so the art comes apart rather than the
/// words simply running out of room. So the header drops to its own line
/// underneath as soon as it no longer fits beside, and a pane too narrow even
/// for the lockup keeps the words and loses the art — at that width the header
/// is the part still carrying information.
///
/// This is `banner`'s layout, and `banner` is its one caller outside the
/// tests: the board draws [`board_masthead`] instead, which keeps the header
/// in the pane's top-right corner. `frame` picks which of `LOCKUP`'s two rows
/// sets is drawn, and `banner` always asks for `0`.
pub(super) fn masthead(header: &str, pane: usize, frame: usize) -> String {
    /// Which lockup line the header sits on when the two fit side by side: the
    /// wordmark's x-height, so the line reads as being on the same line as
    /// the name rather than floating above it.
    const HEADER_LINE: usize = 1;

    let lockup = &LOCKUP[frame];
    let lockup_width = lockup.iter().map(|l| l.chars().count()).max().unwrap_or(0);
    // The gutter between the two, and the frame's own one-column left margin.
    let beside = pane.saturating_sub(1 + lockup_width + 3) >= header.chars().count();

    let mut block = String::new();
    // The margin included: a lockup flush against the right edge is one column
    // from wrapping.
    if lockup_width < pane {
        for (i, line) in lockup.iter().enumerate() {
            // The pad squares up the lockup's ragged right edge so the header
            // starts in one place.
            let pad = " ".repeat(lockup_width - line.chars().count());
            match beside && i == HEADER_LINE {
                true => block.push_str(&format!(
                    " {BOLD}{line}{RESET}{pad}   {DIM}{header}{RESET}\n"
                )),
                false => block.push_str(&format!(" {BOLD}{line}{RESET}\n")),
            }
        }
    }
    if !beside {
        let header = clip(header, pane.saturating_sub(1));
        block.push_str(&format!(" {DIM}{header}{RESET}\n"));
    }
    block
}

/// The lockup and the run's header as the dispatch board draws them: the
/// header right-aligned on the pane's top row, ending one column short of the
/// right edge, whatever the lockup does below it.
///
/// The top row is the lockup's first line, which holds only the `l`'s
/// ascender, so the header shares it whenever both fit with a gutter between
/// them. A pane too narrow for that gives the header a row of its own above
/// the lockup, still right-aligned and clipped with `…` rather than wrapped,
/// because a wrapped header pushes the art down and breaks it. A pane too
/// narrow even for the lockup keeps the header alone, left at the frame's
/// margin as [`masthead`] leaves it, since at that width the words are the
/// part still carrying information.
///
/// `frame` picks which of `LOCKUP`'s two rows sets is drawn: `0` with no
/// dispatcher up and nothing working, [`spool_frame`] otherwise, so the mark
/// turns while a dispatcher is up.
pub(super) fn board_masthead(header: &str, pane: usize, frame: usize) -> String {
    let lockup = &LOCKUP[frame];
    let lockup_width = lockup.iter().map(|l| l.chars().count()).max().unwrap_or(0);

    // The margin included: a lockup flush against the right edge is one column
    // from wrapping.
    if lockup_width >= pane {
        let header = clip(header, pane.saturating_sub(1));
        return format!(" {DIM}{header}{RESET}\n");
    }

    let first = lockup[0];
    let first_width = first.chars().count();
    let header_width = header.chars().count();
    // The frame's one-column left margin, the same three-column gutter
    // `masthead` keeps between art and words, and the one column left free
    // at the right edge.
    let beside = 1 + first_width + 3 + header_width < pane;

    let mut block = String::new();
    let mut lines = lockup.iter();
    if beside {
        lines.next();
        let pad = " ".repeat(pane - 1 - first_width - header_width - 1);
        block.push_str(&format!(" {BOLD}{first}{RESET}{pad}{DIM}{header}{RESET}\n"));
    } else {
        block.push_str(&board_header(header, pane));
    }
    for line in lines {
        block.push_str(&format!(" {BOLD}{line}{RESET}\n"));
    }
    block
}

/// The run's header alone on a row, right-aligned to a pane `pane` columns
/// wide and ending one column short of its right edge — where
/// [`board_masthead`] puts it beside the lockup's first line. A row of its
/// own above the lockup when the two do not fit side by side, and the empty
/// board's whole top row, since [`greeting_screen`] draws its lockup lower
/// down.
pub(super) fn board_header(header: &str, pane: usize) -> String {
    // Both margins come off the room: the header never touches either edge,
    // clipped or not.
    let header = clip(header, pane.saturating_sub(2));
    let pad = " ".repeat(pane.saturating_sub(header.chars().count() + 1));
    format!("{pad}{DIM}{header}{RESET}\n")
}

/// `block` — a masthead or header row already laid out — with `available`,
/// the header's `(<version> available)` notice, painted yellow.
///
/// Painted after the layout rather than carried in the header text, because
/// [`board_masthead`] and [`board_header`] measure and clip the header by its
/// characters, and a colour code inside it would count as columns it does not
/// take. The header is drawn dim, so the notice resets that first and opens
/// it again after: a dim yellow would read as one more grey cell rather than
/// as news. A header clipped through the notice no longer holds it whole, and
/// is left as drawn — a cut-off notice is not one to draw the eye to.
pub(super) fn tint_available(block: &str, available: Option<&str>) -> String {
    match available {
        Some(notice) => block.replacen(notice, &format!("{RESET}{AMBER}{notice}{RESET}{DIM}"), 1),
        None => block.to_string(),
    }
}

/// What an empty board says under its lockup: hello by the local clock's
/// `hour`, and by `name` when there is one — `Good morning, Marvin.`, or
/// `Good morning.` without a name, so the sentence still ends right.
///
/// Takes the hour and the name as plain arguments so every band is tested
/// without the wall clock or the machine's git config. `name` is the first
/// word of git's `user.name` — see [`first_name`].
pub(super) fn greeting(hour: u32, name: Option<&str>) -> String {
    let hello = match hour {
        5..=11 => "Good morning",
        12..=17 => "Good afternoon",
        18..=21 => "Good evening",
        // 22:00 to 04:59, both sides of midnight.
        _ => "Working late",
    };
    match name {
        Some(name) => format!("{hello}, {name}."),
        None => format!("{hello}."),
    }
}

/// The first whitespace-separated word of a git `user.name`, for
/// [`greeting`]. `None` for a value with no word in it at all, so an empty
/// or blank setting greets nobody rather than an empty name.
pub(super) fn first_name(user_name: &str) -> Option<String> {
    user_name.split_whitespace().next().map(str::to_string)
}

/// The rows of the lockup, the blank row under it and the two lines under
/// that — the least an empty board's centred block takes with its art.
const GREETING_BLOCK_ROWS: usize = 5 + 1 + 2;

/// The empty board under its header: the lockup on `frame`, a blank row,
/// `greeting` in bold and `Nothing queued` dim, each centred across a pane
/// `pane` columns wide. Then, when `ledger` has lines, a blank row and the
/// ledger — [`jobs_ledger`]'s lines, which the caller passes only while a
/// dispatcher holds the lock — centred as one block, so its own columns
/// stay lined up under each other.
///
/// The group is centred down `region`: the rows between the header and the
/// key line. A pane too short for the whole group gives up the ledger first,
/// whole, then the lockup: below [`GREETING_BLOCK_ROWS`] the two lines stay
/// alone. A pane too narrow for the lockup drops it too, as [`masthead`]
/// does. `region` is `None` with no terminal to measure: the block then
/// starts one blank row under the header, and one blank row closes it.
///
/// Returns exactly `region` rows when it is known and the group fits, so the
/// key line lands on the pane's own bottom.
pub(super) fn greeting_screen(
    greeting: &str,
    pane: usize,
    region: Option<usize>,
    ledger: &[String],
    frame: usize,
) -> String {
    let lockup = &LOCKUP[frame];
    let lockup_width = lockup.iter().map(|l| l.chars().count()).max().unwrap_or(0);
    let room = region.unwrap_or(usize::MAX);
    // The margin included, as in `masthead`: a lockup flush against the
    // right edge is one column from wrapping.
    let tall_enough = room >= GREETING_BLOCK_ROWS;
    let with_logo = lockup_width < pane && tall_enough;
    // The ledger only ever draws under the lockup. A pane too short or too
    // narrow for the lockup has no ledger either: were the ledger to stand
    // without it, a pane a few rows under the full group's height would
    // drop the ledger, then bring it back once the lockup went, and a
    // person resizing the pane would watch it flicker in and out. Never a
    // part of the ledger, either: half a list reads as jobs that do not
    // exist.
    let with_ledger =
        !ledger.is_empty() && with_logo && room >= GREETING_BLOCK_ROWS + 1 + ledger.len();

    let mut group = String::new();
    if with_logo {
        let left = " ".repeat((pane - lockup_width) / 2);
        for line in lockup {
            group.push_str(&format!("{left}{BOLD}{line}{RESET}\n"));
        }
        group.push('\n');
    }
    for (paint, text) in [(BOLD, greeting), (DIM, "Nothing queued")] {
        // Clipped like the header, one column clear of either edge, so a long
        // first name ends in `…` rather than wrapping off the centre.
        let text = clip(text, pane.saturating_sub(2));
        let left = " ".repeat(pane.saturating_sub(text.chars().count()) / 2);
        group.push_str(&format!("{left}{paint}{text}{RESET}\n"));
    }
    if with_ledger {
        // One margin for every line, off the widest, rather than each line
        // centred on its own: the job lines sit indented under `jobs` by
        // design, and centring them one by one would undo that.
        let width = ledger
            .iter()
            .map(|line| strip_ansi(line).chars().count())
            .max()
            .unwrap_or(0);
        let left = " ".repeat(pane.saturating_sub(width) / 2);
        group.push('\n');
        for line in ledger {
            group.push_str(&format!("{left}{line}\n"));
        }
    }

    let Some(region) = region else {
        return format!("\n{group}\n");
    };
    let rows = group.lines().count();
    let top = region.saturating_sub(rows) / 2;
    let bottom = region.saturating_sub(rows + top);
    format!("{}{group}{}", "\n".repeat(top), "\n".repeat(bottom))
}

/// The lockup with one line of prose beside it, for a command that introduces
/// itself before it does anything.
///
/// `init` is the one caller, and the reason it goes through [`masthead`]
/// rather than printing `LOCKUP` itself is that there is one piece of art
/// here: whatever the generator draws next, this and the board's
/// [`board_masthead`] both draw it without either knowing about the other.
/// The two lay the words out differently — beside the wordmark here, in the
/// pane's top-right corner on the board — because this line introduces a
/// command rather than reporting a run.
///
/// Empty when stdout is not a terminal. The escapes it carries are noise in
/// a pipe, and `init`'s output is read by scripts.
pub fn banner(header: &str) -> String {
    use std::io::IsTerminal;
    match std::io::stdout().is_terminal() {
        true => masthead(header, pane_width(), 0),
        false => String::new(),
    }
}

/// Which of `LOCKUP`'s two frames a board draws, while `running` is true —
/// a dispatcher holds the lock, or a lane is working; frame 0, held, the
/// moment neither is.
///
/// A function of the wall clock alone, not a counter this call increments —
/// the same instant lands on the same frame whichever redraw reads it.
/// Flips on every whole second rather than every draw, so redrawing more or
/// less often — the wait loop's `POLL`, a pass, the final frame — never
/// changes what the spool does.
pub(super) fn spool_frame(running: bool) -> usize {
    if !running {
        return 0;
    }
    let secs = SystemTime::now()
        .duration_since(SystemTime::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    spool_phase(secs)
}

/// The half of [`spool_frame`] that takes the clock as a plain number, so the
/// arithmetic is checked without a test having to control real time.
fn spool_phase(elapsed_secs: u64) -> usize {
    (elapsed_secs % 2) as usize
}

/// How wide the pane is, for the one column that has to fit in what is left.
///
/// Asked fresh every frame, so resizing the pane reflows the next redraw.
/// The fallback is generous rather than tight: with no terminal to ask —
/// output piped somewhere — clipping is not protecting any layout.
///
/// Inside bare `spoolway`'s dispatch tab the width is the drawing area's —
/// see [`crate::screen::drawing_area`] — and the board draws inside a box
/// there — see [`boxed`] — whose two side borders come off it too, so every
/// row is laid out against the columns between them.
pub(super) fn pane_width() -> usize {
    let width = crate::screen::drawing_area()
        .map(|(width, _)| width)
        .unwrap_or(120);
    match crate::screen::shell::hosted() {
        Some(_) => width.saturating_sub(BOX_SIDES),
        None => width,
    }
}

/// The columns the box around the hosted board takes, and the rows: one
/// border on each side, and one border above and below.
const BOX_SIDES: usize = 2;

/// How tall the pane is, or `None` where there is no terminal to ask.
///
/// Asked fresh every frame for the same reason as the width. `None` is not a
/// fallback height: output that is not a terminal has no bottom to fall off,
/// and a board redirected to a file should keep every line it was going to
/// write rather than being cut to a guess.
///
/// Inside bare `spoolway`'s dispatch tab the height is the drawing area's —
/// see [`crate::screen::drawing_area`] — the tab strip takes its own rows
/// off the top of it — see `crate::screen::shell::strip_rows`, zero
/// everywhere else — and the box the board draws in there takes its top and
/// bottom borders — see [`boxed`] — so the board is measured against what
/// is actually left inside it. Left uncounted, the two borders push the
/// board's foot under the key line and the top of the frame off the screen.
/// Each row the key line wraps onto past its first comes off as well, where
/// the key line is built — see `paint_at`.
///
/// A test build answers `None`, as if piped, unless the test names a
/// terminal — see [`crate::screen::test_terminal`].
pub(super) fn pane_height() -> Option<usize> {
    let boxed = match crate::screen::shell::hosted() {
        Some(_) => BOX_SIDES,
        None => 0,
    };
    crate::screen::drawing_area()
        .map(|(_, height)| height.saturating_sub(crate::screen::shell::strip_rows() + boxed))
}

/// The hosted board's `body` inside a box with no title, `inner` columns
/// between its borders, with `keys` — the key line, one row or several —
/// under the bottom border, the way the queue, jobs and eval tabs draw
/// theirs.
///
/// `height` is [`pane_height`]'s own, less any row `keys` wraps onto past
/// its first: the body gets every row of it but the one the key line takes
/// and the spare row left under it, cut to fit or padded with blank rows so
/// the box always reaches the same bottom row. `None` — no terminal to
/// measure — keeps every body row and pads none.
///
/// Each row is fitted to `inner` by its visible width — see [`fit_visible`]
/// — so a row carrying colour codes or a hyperlink still ends in `│` in the
/// drawing area's last column rather than as far right as its escape bytes
/// would count.
pub(super) fn boxed(body: &str, keys: &str, inner: usize, height: Option<usize>) -> String {
    use crate::screen::corner::{BOTTOM_LEFT, BOTTOM_RIGHT, TOP_LEFT, TOP_RIGHT};
    let mut rows: Vec<&str> = body.lines().collect();
    if let Some(height) = height {
        let room = height.saturating_sub(2);
        rows.truncate(room);
        rows.resize(room, "");
    }
    let mut out = format!("{TOP_LEFT}{}{TOP_RIGHT}\n", "─".repeat(inner));
    for row in rows {
        out.push_str(&format!("│{}│\n", fit_visible(row, inner)));
    }
    out.push_str(&format!(
        "{BOTTOM_LEFT}{}{BOTTOM_RIGHT}\n",
        "─".repeat(inner)
    ));
    out.push_str(keys);
    out.push('\n');
    out
}

/// `line` cut or padded to exactly `width` visible characters, its escape
/// codes kept whole and counted as no width at all — the same codes
/// [`strip_ansi`] reads past. A line cut short has its colour reset and any
/// hyperlink it opened closed, so neither runs on into the border after it.
fn fit_visible(line: &str, width: usize) -> String {
    let mut out = String::new();
    let mut shown = 0;
    let mut escaped = false;
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' {
            escaped = true;
            out.push(c);
            if chars.peek() == Some(&']') {
                // An OSC sequence ends on `ESC \` or a bare BEL — see
                // `strip_ansi` for why never on an `m`.
                while let Some(c) = chars.next() {
                    out.push(c);
                    match c {
                        '\u{7}' => break,
                        '\u{1b}' => {
                            out.extend(chars.next());
                            break;
                        }
                        _ => {}
                    }
                }
            } else {
                for c in chars.by_ref() {
                    out.push(c);
                    if c == 'm' {
                        break;
                    }
                }
            }
            continue;
        }
        if shown == width {
            // Cut here: a hyperlink closed with its target left empty is
            // the one form every terminal reads as "link ends", open or not.
            if escaped {
                out.push_str(&format!("{OSC8}{ST}{RESET}"));
            }
            return out;
        }
        out.push(c);
        shown += 1;
    }
    out.push_str(&" ".repeat(width - shown));
    out
}

/// `text` cut to `room` visible characters, ending in `…` when anything had
/// to go. Characters, not bytes: what is cut here is never guaranteed ASCII —
/// a task id, a step name, a row's own NEXT text — and `…` mid-codepoint is a
/// panic, not an ellipsis.
fn clip(text: &str, room: usize) -> String {
    if text.chars().count() <= room {
        return text.to_string();
    }
    let kept: String = text.chars().take(room.saturating_sub(1)).collect();
    format!("{}…", kept.trim_end())
}

/// The ticker, cut to the rows it has been left and to the width of the pane.
///
/// A frame is drawn by clearing the screen and printing over it, which holds
/// only while the frame fits on that screen. One line too many and the
/// terminal scrolls to make room, and what scrolls off the top is in the
/// scrollback for good — so a board that looks right at the bottom of the pane
/// has been stacking a fresh lockup behind itself, one per pass, for as long
/// as it has been running.
///
/// The ticker is what gives first. The lockup is fixed and the footer is one
/// line per agent profile, and the board's task table scrolls rather than
/// give up its cursor's row — see [`table_window`] — so the ticker is drawn
/// only when the whole table fits, in the rows the table leaves. Its oldest
/// arrival is the line nobody is reading.
pub(super) fn ticker(recent: &VecDeque<RecentEvent>, pane: usize, rows: usize) -> String {
    // Two of the rows go to the blank line and the `RECENT` heading. Anything
    // less than three of them cannot show an arrival under that heading, and
    // a heading over nothing is worth less than the row it would cost.
    if recent.is_empty() || rows < 3 {
        return String::new();
    }

    // `recent` keeps the oldest move first; the newest is drawn on top, so
    // the rows a short pane cannot hold come off the bottom of the block.
    let shown = (rows - 2).min(recent.len());
    let events: Vec<&RecentEvent> = recent.iter().rev().take(shown).collect();

    // The name column sized to the rows about to be drawn, not to a fixed
    // guess — the same reason the table's own STATE column is only as wide
    // as the states actually on the board (see
    // `the_state_column_is_only_as_wide_as_the_states_on_the_board`).
    let name_width = events
        .iter()
        .map(|event| event.name().chars().count())
        .max()
        .unwrap_or(0);

    let mut block = format!("\n {DIM}RECENT{RESET}\n");
    for event in events {
        let RecentEvent::Arrival { at, change, .. } = event;
        let plain = recent_line(at, event.name(), name_width, &sentence(change));
        // Cut to the pane, less the one leading column, so a sentence too
        // long for it ends in `…` rather than wrapping onto the next row.
        let plain = clip(&plain, pane.saturating_sub(1));
        block.push_str(&format!(" {DIM}{plain}{RESET}\n"));
    }
    block
}

/// One RECENT line before it is clipped and dimmed: the time, the task's
/// [`RecentEvent::name`] padded to `name_width`, then the sentence. Apart
/// from [`ticker`] so a test can lay out a sentence [`sentence`] does not
/// draw yet against the same columns.
fn recent_line(at: &str, name: &str, name_width: usize, sentence: &str) -> String {
    format!("{at}{GUTTER}{name:<name_width$}{GUTTER}{sentence}")
}

/// The sentence a RECENT line says about one move. Every word the ticker
/// prints about a move is written here and nowhere else, so two kinds of
/// move can never drift into two phrasings of the same thing. Each sentence
/// names what happened on which step first and where the task went last,
/// as `moved to <step>`, then the cause in brackets when there is one. A
/// failed hook is the one exception: the task's STEP stays where the hook
/// stopped it, so the sentence names the hook and why it failed instead.
pub(crate) fn sentence(change: &Move) -> String {
    use crate::pipeline::PAUSED;

    let (said, cause) = match change {
        Move::Started { to } => (format!("started, moved to {to}"), None),
        Move::Passed { from, to, cause } => {
            (format!("passed {from}, moved to {to}"), cause.as_ref())
        }
        Move::Failed { from, to, cause } => {
            (format!("failed {from}, moved to {to}"), cause.as_ref())
        }
        Move::Skipped { from, to, cause } => {
            (format!("skipped {from}, moved to {to}"), cause.as_ref())
        }
        Move::Reported {
            what,
            from,
            to,
            cause,
        } => {
            let what = match what {
                Reported::Block => "block",
                Reported::Pause => "pause",
            };
            (
                format!("reported a {what} on {from}, moved to {to}"),
                cause.as_ref(),
            )
        }
        Move::CouldNotLaunch { from, to, cause } => (
            format!("could not launch {from}, moved to {to}"),
            cause.as_ref(),
        ),
        Move::Stopped {
            from: Some(from),
            cause,
        } => (
            format!("stopped on {from}, moved to {PAUSED}"),
            cause.as_ref(),
        ),
        Move::Stopped { from: None, cause } => (
            format!("stopped before starting, moved to {PAUSED}"),
            cause.as_ref(),
        ),
        Move::Escalated { from, to } => (
            format!("stopped on {from}, moved to {to}"),
            Some(&Cause::Escalated),
        ),
        Move::HookFailed {
            passed,
            event,
            reason,
        } => {
            let passed = passed
                .as_ref()
                .map(|step| format!("passed {step}, "))
                .unwrap_or_default();
            let hook = event
                .as_ref()
                .map(|event| format!("{event} hook failed"))
                .unwrap_or_else(|| "hook failed".to_string());
            let why = reason
                .as_ref()
                .map(|reason| format!(": {reason}"))
                .unwrap_or_default();
            (format!("{passed}{hook}{why}"), None)
        }
        Move::HookSkipped { event, to: None } => (format!("skipped {event} hook, archived"), None),
        Move::HookSkipped {
            event,
            to: Some(to),
        } => (format!("skipped {event} hook, moved to {to}"), None),
        Move::Resumed { to } => (format!("resumed, moved to {to}"), None),
        Move::Unblocked { to, by_lane: false } => (format!("unblocked, moved to {to}"), None),
        Move::Unblocked { to, by_lane: true } => {
            (format!("unblocked by its lane, moved to {to}"), None)
        }
        Move::Left { from, to } => (format!("left {from}, moved to {to}"), None),
    };
    match cause {
        Some(cause) => format!("{said} ({})", cause.words()),
        None => said,
    }
}

/// `frame` cut to the rows a pane of `height` can hold without scrolling.
///
/// The backstop under [`ticker`] and [`table_window`], for the frame that
/// does not fit even with an empty ticker and a table of no rows: a pane
/// shorter than the lockup, the footer and the key line together. Something
/// has to go, and it is the bottom — what the run is doing outranks what it
/// has spent.
///
/// One row is held back because every line here ends in a newline, the last
/// one included: a frame filling the pane exactly would park the cursor one
/// row below the bottom, which scrolls, which is the whole thing being
/// avoided.
pub(super) fn clamp_rows(frame: &str, height: Option<usize>) -> String {
    let Some(height) = height else {
        return frame.to_string();
    };
    let room = height.saturating_sub(1);
    if frame.lines().count() <= room {
        return frame.to_string();
    }
    frame
        .lines()
        .take(room)
        .map(|line| format!("{line}\n"))
        .collect()
}

/// A line as a reader sees it, with the escape codes taken out whole — an
/// `m` inside `12m 03s` is not a code ending, and neither is one inside the
/// url of a group band's hyperlink.
///
/// Used only where a confirm panel is drawn over the board: [`crate::screen::overlay`]
/// writes a panel row by walking a target row's own characters, escape bytes
/// included, so it has no way to line a panel's *visible* columns up with a
/// coloured row's — a `DIM`/`RESET` pair sliced apart by a panel row reads
/// back as stray digits and letters, not as the colour it opened. A panel
/// carries no colour of its own, so the frame beneath one can afford to lose
/// its while it is up; the next frame, once the panel closes, is read fresh
/// and in colour again.
pub(crate) fn strip_ansi(text: &str) -> String {
    let mut out = String::new();
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        if c != '\u{1b}' {
            out.push(c);
            continue;
        }
        if chars.peek() == Some(&']') {
            // An OSC sequence — the group band's `ESC ] 8 ; ; <url> ESC \`
            // hyperlink is the only one drawn here. It ends on `ESC \` (ST)
            // or a bare BEL, never on an `m`, so a url with an `m` in it
            // would end an `m`-terminated skip early and leak the rest of
            // the url into the panel over the board.
            while let Some(c) = chars.next() {
                match c {
                    '\u{7}' => break,
                    '\u{1b}' => {
                        chars.next(); // the `\` closing `ESC \`
                        break;
                    }
                    _ => {}
                }
            }
        } else {
            // A CSI colour code: skip to its `m` terminator.
            for c in chars.by_ref() {
                if c == 'm' {
                    break;
                }
            }
        }
    }
    out
}

/// Seconds as the shortest honest clock reading: `47s`, `12m 03s`, `1h 04m`.
///
/// Crate-visible so [`crate::eval`] spells a row's lane time the
/// same way the board does — one clock reading, not two competing ones.
pub(crate) fn human_secs(total: i64) -> String {
    let (h, m, s) = (total / 3600, (total % 3600) / 60, total % 60);
    match (h, m) {
        (0, 0) => format!("{s}s"),
        (0, _) => format!("{m}m {s:02}s"),
        _ => format!("{h}h {m:02}m"),
    }
}

