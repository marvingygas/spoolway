//! The loading spool: the mark alone, in cyan, turned over a tab while a
//! key's work runs.
//!
//! Keys and drawing share one thread, so a key whose work takes a second or
//! more leaves the last frame frozen on screen for the whole wait, and a
//! person who sees nothing happen presses the key again. [`under_spool`]
//! runs that work where it always ran, on the loop thread, and starts a
//! short-lived drawing thread beside it that turns the spool over the last
//! frame [`FrameWriter`] wrote. Moving the work instead would rewrite every
//! handler that owns its tab's state, to show the same picture.
//!
//! The drawing thread is the only thing that writes while the work runs —
//! the work is handed no writer and no output — and it is stopped and
//! joined before the work's result goes back to the loop. So the two never
//! write to the terminal at once, and whatever the work hands back, a
//! pop-up of its own included, is drawn with the spool already gone.

use std::sync::mpsc;
use std::time::{Duration, Instant};

use super::PollableRead;
use super::frame_writer::FrameWriter;

/// How long the work runs before the spool shows. A key that finishes
/// sooner draws nothing, so a quick key never flashes the spool up.
pub(crate) const DELAY: Duration = Duration::from_millis(200);

/// How long each frame of the mark stays up before the other replaces it:
/// four times the board masthead's once a second, so even a one-second
/// wait visibly turns.
pub(crate) const FLIP: Duration = Duration::from_millis(250);

/// The least time the spool stays up once it has shown, however soon the
/// work returns after it, so it never flickers on and straight off.
pub(crate) const HOLD: Duration = Duration::from_millis(250);

/// The mark alone, with no wordmark, as half-block art: six columns by three
/// rows, one row set per frame of the mark.
///
/// Generated by `docs/logo/generate_board.py` from `GRID` and `GRID_B` in
/// `docs/logo/mark.py`; `the_spool_art_is_what_the_generator_draws` fails if
/// this constant and that script disagree, so it is never edited by hand.
/// Paste the `SPOOL` constant the script prints. Drawn at the mark's shipped size and never
/// scaled — see `docs/logo/README.md` on whole numbers only.
const SPOOL: [[&str; 3]; 2] = [
    ["▀█▀██▀", " █▀▄█ ", "▄██▄█▄"],
    ["▀██▀█▀", " █▄▀█ ", "▄█▄██▄"],
];

/// The patch the spool is drawn on: one blank column either side of the
/// mark and one blank row above and below, so none of the dimmed tab shows
/// through the gaps in its thread or crowds its flanges.
const PATCH_WIDTH: usize = 8;
const PATCH_HEIGHT: usize = 5;

/// `frame` of the mark on its blank patch, as rows [`spool_frame`] lays over
/// a tab.
fn patch(frame: usize) -> Vec<String> {
    let blank = " ".repeat(PATCH_WIDTH);
    let mut rows = vec![blank.clone()];
    rows.extend(SPOOL[frame].iter().map(|row| format!(" {row} ")));
    rows.push(blank);
    rows
}

/// Cyan on every inked character of the patch's `i`th row and nothing on its
/// blanks — the colour of every pop-up's border, which no board state is,
/// so the spool never reads as part of the rows behind it.
fn cyan(patch: &[String], i: usize) -> Vec<Option<&'static str>> {
    patch[i]
        .chars()
        .map(|c| (c != ' ').then_some(crate::status::CYAN))
        .collect()
}

/// `last` dimmed, with `frame` of the spool on its patch in the middle — the
/// same centring every pop-up is laid down with, see [`super::overlay`].
///
/// Measured across `last`'s widest row, not its first: the frames a tab
/// writes inside bare `spoolway` open on the blank row above the tab strip,
/// so the first row is empty and would put the patch nowhere.
///
/// Every row is padded out to that width first. [`super::overlay`] writes
/// nothing past a row's last character, and those frames also leave the row
/// under the tab strip empty, so on a short pane, where the patch lands on
/// that row, the mark would lose its top row.
///
/// `None` when `last` is narrower than the patch, or not a row taller than
/// it, since the patch is never laid over the first row: a pane that small
/// has nowhere to put the whole spool, so it draws none, and the next normal
/// frame is drawn at whatever size the pane is by then.
fn spool_frame(last: &[String], frame: usize) -> Option<Vec<String>> {
    let width = last
        .iter()
        .map(|row| crate::status::strip_ansi(row).chars().count())
        .max()?;
    if width < PATCH_WIDTH || last.len() < PATCH_HEIGHT + 1 {
        return None;
    }
    let mut rows = last.to_vec();
    super::dim(&mut rows);
    for row in &mut rows {
        *row = super::pad_visible(row, width);
    }
    super::overlay_painted(&mut rows, &patch(frame), width, cyan);
    Some(rows)
}

/// Which of the mark's two frames shows `elapsed` into the work: `None`
/// before [`DELAY`], then frame 0 and frame 1 in turn, [`FLIP`] each.
fn frame_at(elapsed: Duration) -> Option<usize> {
    let up = elapsed.checked_sub(DELAY)?;
    Some((up.as_nanos() / FLIP.as_nanos() % 2) as usize)
}

/// How long after `elapsed` [`frame_at`] next changes its answer — what the
/// drawing thread waits for a stop for before it draws again.
fn until_change(elapsed: Duration) -> Duration {
    match elapsed.checked_sub(DELAY) {
        None => DELAY - elapsed,
        Some(up) => FLIP - Duration::from_nanos((up.as_nanos() % FLIP.as_nanos()) as u64),
    }
}

/// How much longer the spool stays up once the work ended at `ended`, having
/// first shown at `shown` — both measured from the work's start.
fn hold_left(shown: Duration, ended: Duration) -> Duration {
    (shown + HOLD).saturating_sub(ended)
}

/// The drawing thread: turn the spool over the last frame `writer` wrote
/// until `stop` says the work is done, then hold it up out to [`HOLD`].
/// Whether the spool was ever drawn.
///
/// A dropped sender stops it the same as a sent stop, so a work that panics
/// never leaves this turning while the scope it runs in waits to join it.
fn turn(
    writer: &mut FrameWriter,
    out: &mut impl std::io::Write,
    stop: mpsc::Receiver<()>,
    start: Instant,
) -> bool {
    // Nothing written yet means nothing on screen to lay the spool over.
    let Some((last, pane)) = writer.last().cloned() else {
        return false;
    };
    let mut drawn = None;
    let mut shown = None;
    loop {
        let elapsed = start.elapsed();
        if let Some(frame) = frame_at(elapsed)
            && drawn != Some(frame)
        {
            let Some(rows) = spool_frame(&last, frame) else {
                return false;
            };
            // Placed from the last frame's own size, and written for the
            // pane that frame was: a resize during the wait is answered by
            // the loop's next normal frame, not by this one.
            writer.write_frame(&rows, pane, out);
            drawn = Some(frame);
            shown.get_or_insert(elapsed);
        }
        match stop.recv_timeout(until_change(start.elapsed())) {
            Err(mpsc::RecvTimeoutError::Timeout) => {}
            Ok(()) | Err(mpsc::RecvTimeoutError::Disconnected) => break,
        }
    }
    let Some(shown) = shown else {
        return false;
    };
    std::thread::sleep(hold_left(shown, start.elapsed()));
    true
}

/// Run `work` on this thread with the loading spool turning over the tab
/// while it does, and answer what it returned.
///
/// The spool shows only once `work` has run for [`DELAY`]; until then, and
/// for a key that never takes that long, nothing is drawn. Once it has
/// shown, every key typed during the work is thrown away when it ends, the
/// way the issue-hook progress pop-up already throws them away: a person who
/// pressed `enter` again because nothing seemed to happen meant it for this
/// screen, not for whatever the work hands back. A spool that never showed
/// leaves typed keys exactly where they were.
///
/// `work` must not write to the terminal itself — it is handed neither
/// `writer` nor `out`, which belong to the drawing thread until it returns.
pub(crate) fn under_spool<T>(
    writer: &mut FrameWriter,
    out: &mut (impl std::io::Write + Send),
    input: &mut impl PollableRead,
    work: impl FnOnce() -> T,
) -> T {
    let start = Instant::now();
    let (stop, stopped) = mpsc::channel();
    let (result, shown) = std::thread::scope(|scope| {
        // Moved in so a panic in `work` drops it on the way out of this
        // closure, which stops the drawing thread before the scope joins it.
        let stop = stop;
        let turning = scope.spawn(move || turn(writer, out, stopped, start));
        let result = work();
        let _ = stop.send(());
        // A drawing thread that panicked drew no spool anyone needs to
        // answer for; the work's own result still goes back.
        (result, turning.join().unwrap_or(false))
    });
    if shown {
        input.discard_typed();
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::status::{CYAN, DIM, strip_ansi};

    fn ms(n: u64) -> Duration {
        Duration::from_millis(n)
    }

    /// A tab `width` columns by `height` rows with every cell inked, so a
    /// cell the patch failed to clear shows up as an `x`.
    fn tab(width: usize, height: usize) -> Vec<String> {
        vec!["x".repeat(width); height]
    }

    #[test]
    fn the_spool_waits_out_the_delay_before_it_shows() {
        assert_eq!(frame_at(Duration::ZERO), None);
        assert_eq!(frame_at(ms(199)), None);
        assert_eq!(frame_at(ms(200)), Some(0));
        assert_eq!(until_change(Duration::ZERO), ms(200));
        assert_eq!(until_change(ms(120)), ms(80));
    }

    #[test]
    fn the_spool_flips_every_quarter_second_once_up() {
        assert_eq!(frame_at(ms(449)), Some(0));
        assert_eq!(frame_at(ms(450)), Some(1));
        assert_eq!(frame_at(ms(699)), Some(1));
        assert_eq!(frame_at(ms(700)), Some(0));
        assert_eq!(frame_at(ms(2400)), Some(0));
        assert_eq!(until_change(ms(200)), ms(250));
        assert_eq!(until_change(ms(300)), ms(150));
        assert_eq!(until_change(ms(450)), ms(250));
    }

    #[test]
    fn the_spool_stays_up_at_least_the_hold_once_shown() {
        // Shown at 200 ms, work back at 300 ms: held out to 450 ms.
        assert_eq!(hold_left(ms(200), ms(300)), ms(150));
        assert_eq!(hold_left(ms(200), ms(450)), Duration::ZERO);
        assert_eq!(hold_left(ms(200), ms(2400)), Duration::ZERO);
    }

    #[test]
    fn the_patch_is_the_mark_on_eight_columns_by_five_rows_of_blank() {
        for (frame, art) in SPOOL.iter().enumerate() {
            let patch = patch(frame);
            assert_eq!(patch.len(), PATCH_HEIGHT);
            for row in &patch {
                assert_eq!(row.chars().count(), PATCH_WIDTH, "{row:?}");
            }
            assert_eq!(patch[0].trim(), "");
            assert_eq!(patch[4].trim(), "");
            for (row, art) in patch[1..4].iter().zip(art) {
                assert_eq!(row, &format!(" {art} "));
            }
        }
    }

    #[test]
    fn the_spool_is_centred_on_a_cleared_patch_over_the_dimmed_tab() {
        let drawn = spool_frame(&tab(40, 12), 0).unwrap();
        let plain: Vec<String> = drawn.iter().map(|row| strip_ansi(row)).collect();
        // `overlay`'s centring: (40 - 8) / 2 across, (12 - 5) / 2 down.
        let (x, y) = (16, 3);
        for (i, row) in plain.iter().enumerate() {
            let cells: Vec<char> = row.chars().collect();
            assert_eq!(cells.len(), 40, "{row}");
            let patch_row = i.checked_sub(y).filter(|r| *r < PATCH_HEIGHT);
            match patch_row {
                Some(r) => {
                    let over: String = cells[x..x + PATCH_WIDTH].iter().collect();
                    assert_eq!(over, patch(0)[r], "row {i}");
                    assert!(cells[..x].iter().all(|c| *c == 'x'), "row {i}");
                    assert!(
                        cells[x + PATCH_WIDTH..].iter().all(|c| *c == 'x'),
                        "row {i}"
                    );
                }
                None => assert_eq!(row, &"x".repeat(40), "row {i}"),
            }
        }
        // The tab behind is dimmed, every row of it.
        for row in &drawn {
            assert!(row.starts_with(DIM), "{row:?}");
        }
        // The mark is cyan, its row opening the colour where its ink starts.
        assert!(
            drawn[y + 1].contains(&format!("{CYAN}{}", SPOOL[0][0])),
            "{:?}",
            drawn[y + 1]
        );
        assert!(
            drawn[y + 2].contains(&format!("{CYAN}{}", SPOOL[0][1].trim())),
            "{:?}",
            drawn[y + 2]
        );
        // The blank rows of the patch carry no cyan at all.
        assert!(!drawn[y].contains(CYAN), "{:?}", drawn[y]);
        assert!(!drawn[y + 4].contains(CYAN), "{:?}", drawn[y + 4]);
    }

    /// The shape of every frame a tab writes inside bare `spoolway`: a blank
    /// row above the tab strip, then the tab. Measured from that first row,
    /// the tab is no columns wide and the spool is never drawn.
    #[test]
    fn the_spool_is_centred_on_a_tab_whose_first_row_is_blank() {
        let mut last = tab(40, 12);
        last[0] = String::new();
        let drawn = spool_frame(&last, 0).expect("no spool over a tab with a blank first row");
        let plain: Vec<String> = drawn.iter().map(|row| strip_ansi(row)).collect();
        assert_eq!(plain[0].trim(), "");
        let (x, y) = (16, 3);
        for (r, want) in patch(0).iter().enumerate() {
            let over: String = plain[y + r].chars().skip(x).take(PATCH_WIDTH).collect();
            assert_eq!(&over, want, "row {}", y + r);
        }
    }

    #[test]
    fn the_second_frame_draws_the_other_phase_of_the_thread() {
        let drawn = spool_frame(&tab(40, 12), 1).unwrap();
        let plain = strip_ansi(&drawn[4]);
        assert!(plain.contains(SPOOL[1][0]), "{plain}");
        assert!(!plain.contains(SPOOL[0][0]), "{plain}");
    }

    #[test]
    fn a_pane_smaller_than_the_patch_draws_no_spool() {
        assert_eq!(spool_frame(&tab(7, 12), 0), None);
        assert_eq!(spool_frame(&tab(40, 4), 0), None);
        assert_eq!(spool_frame(&tab(40, 5), 0), None);
        assert_eq!(spool_frame(&[], 0), None);
        assert!(spool_frame(&tab(8, 6), 0).is_some());
    }

    /// A pane only just tall enough, shaped the way bare `spoolway`'s frames
    /// are: the blank row above the tab strip, the strip, and the empty row
    /// under it. The patch lands one row down, its top on the strip and the
    /// mark's first row on that empty row, and every cell of it is drawn.
    #[test]
    fn a_short_pane_draws_the_whole_patch_over_empty_rows() {
        for height in 6..=8 {
            let mut last = tab(40, height);
            last[0] = String::new();
            last[2] = String::new();
            let drawn = spool_frame(&last, 0).expect("no spool on a short pane");
            let plain: Vec<String> = drawn.iter().map(|row| strip_ansi(row)).collect();
            for (r, want) in patch(0).iter().enumerate() {
                let over: String = plain[1 + r].chars().skip(16).take(PATCH_WIDTH).collect();
                assert_eq!(&over, want, "{height} rows, row {}", 1 + r);
            }
            assert!(
                drawn[2].contains(&format!("{CYAN}{}", SPOOL[0][0])),
                "{:?}",
                drawn[2]
            );
        }
    }

    /// A reader with nothing to read that remembers being asked to throw
    /// typed keys away.
    #[derive(Default)]
    struct Typed {
        discarded: bool,
    }

    impl std::io::Read for Typed {
        fn read(&mut self, _: &mut [u8]) -> std::io::Result<usize> {
            Ok(0)
        }
    }

    impl PollableRead for Typed {
        fn byte_pending(&self, _: Duration) -> bool {
            true
        }

        fn discard_typed(&mut self) {
            self.discarded = true;
        }
    }

    /// A writer holding one frame already, the way a tab's writer does by the
    /// time a key is pressed on it — blank first row and all, as inside bare
    /// `spoolway`.
    fn written() -> FrameWriter {
        let mut last = tab(40, 12);
        last[0] = String::new();
        let mut writer = FrameWriter::new();
        writer.write_frame(&last, (41, 12), &mut Vec::new());
        writer
    }

    #[test]
    fn quick_work_draws_nothing_and_keeps_typed_keys() {
        let mut writer = written();
        let (mut out, mut input) = (Vec::new(), Typed::default());
        let answer = under_spool(&mut writer, &mut out, &mut input, || 7);
        assert_eq!(answer, 7);
        assert!(out.is_empty(), "{}", String::from_utf8_lossy(&out));
        assert!(!input.discarded);
    }

    /// The terminal the drawing thread writes to, which says on `drew` each
    /// frame of the mark it has seen written, so a work can wait for the
    /// spool itself rather than sleep for as long as it ought to take.
    struct Watched {
        bytes: Vec<u8>,
        drew: mpsc::Sender<usize>,
    }

    impl std::io::Write for Watched {
        fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
            let text = String::from_utf8_lossy(buf);
            for (frame, art) in SPOOL.iter().enumerate() {
                if text.contains(art[0]) {
                    let _ = self.drew.send(frame);
                }
            }
            self.bytes.extend_from_slice(buf);
            Ok(buf.len())
        }

        fn flush(&mut self) -> std::io::Result<()> {
            Ok(())
        }
    }

    /// A [`Watched`] terminal, and what it says it drew.
    fn watched() -> (Watched, mpsc::Receiver<usize>) {
        let (drew, seen) = mpsc::channel();
        let out = Watched {
            bytes: Vec::new(),
            drew,
        };
        (out, seen)
    }

    /// How long a work waits for the spool before it gives up on it. Only a
    /// backstop, so a broken spool fails the test rather than hanging it.
    const BACKSTOP: Duration = Duration::from_secs(10);

    /// The work runs until the drawing thread has written frame B, however
    /// long a loaded machine takes to get there.
    #[test]
    fn slow_work_turns_the_spool_and_drops_typed_keys() {
        let mut writer = written();
        let ((mut out, seen), mut input) = (watched(), Typed::default());
        let answer = under_spool(&mut writer, &mut out, &mut input, || {
            while seen.recv_timeout(BACKSTOP).expect("frame B never drawn") != 1 {}
            "queued"
        });
        assert_eq!(answer, "queued");
        let drawn = String::from_utf8_lossy(&out.bytes);
        let a = drawn.find(SPOOL[0][0]).expect("frame A never drawn");
        let b = drawn.find(SPOOL[1][0]).expect("frame B never drawn");
        assert!(a < b, "frame B drawn before frame A");
        assert!(drawn.contains(CYAN), "{drawn}");
        assert!(input.discarded);
    }

    /// The work returns the moment frame A is on screen, and the spool is
    /// still held up out to the hold. The spool cannot show before the delay
    /// and the hold is a sleep, so the bound holds on any machine.
    #[test]
    fn the_spool_is_held_up_when_the_work_returns_just_after_it_shows() {
        let mut writer = written();
        let ((mut out, seen), mut input) = (watched(), Typed::default());
        let start = Instant::now();
        under_spool(&mut writer, &mut out, &mut input, || {
            seen.recv_timeout(BACKSTOP).expect("frame A never drawn");
        });
        let took = start.elapsed();
        assert!(took >= DELAY + HOLD, "the spool came down after {took:?}");
        assert!(input.discarded);
    }

    #[test]
    fn nothing_written_yet_draws_no_spool() {
        let mut writer = FrameWriter::new();
        let (mut out, mut input) = (Vec::new(), Typed::default());
        under_spool(&mut writer, &mut out, &mut input, || {
            std::thread::sleep(ms(300));
        });
        assert!(out.is_empty());
        assert!(!input.discarded);
    }

    /// The spool's art is generated, the same way the board's lockup is — see
    /// `the_board_art_is_what_the_generator_draws` in `status::view`, whose
    /// reasons all apply here.
    ///
    /// The script prints `SPOOL` ahead of `LOCKUP`, so the art is the quoted
    /// lines between the two: frame A's three rows, then frame B's. Skips,
    /// rather than fails, when the generator cannot run at all — no
    /// `python3`, no Pillow.
    #[test]
    fn the_spool_art_is_what_the_generator_draws() {
        let logo = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/logo");
        let out = match std::process::Command::new("python3")
            .arg("generate_board.py")
            .current_dir(&logo)
            .output()
        {
            Ok(out) if out.status.success() => String::from_utf8_lossy(&out.stdout).into_owned(),
            _ => return,
        };

        let tail = out
            .split_once("const SPOOL")
            .expect("no constant printed")
            .1;
        let body = tail
            .split_once("const LOCKUP")
            .map_or(tail, |(body, _)| body);
        let drawn: Vec<&str> = body
            .lines()
            .filter_map(|line| line.trim().strip_prefix('"')?.strip_suffix("\","))
            .collect();

        let expected: Vec<&str> = SPOOL.iter().flatten().copied().collect();
        assert_eq!(
            drawn, expected,
            "the spool's art and docs/logo/generate_board.py disagree — paste the SPOOL constant the script prints"
        );
    }
}
